import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
const base = process.env.CREWVELA_UI_URL || 'http://127.0.0.1:1420';
const out = '.scratch/new-team-conversation-20261117';
mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const errors = [];
const trigger = page => page.getByRole('button', { name: '讨论记录操作', exact: true });
const newItem = page => page.getByRole('menuitem', { name: '新建会话', exact: true });
const historyItem = page => page.getByRole('menuitem', { name: '历史会话', exact: true });
const exportItem = page => page.getByRole('menuitem', { name: '导出会话', exact: true });
const clearItem = page => page.getByRole('menuitem', { name: '清空讨论记录', exact: true });
const editor = page => page.locator('textarea');
async function fresh(query = '', width = 780) {
  const page = await browser.newPage({ viewport: { width, height: 1000 } });
  page.setDefaultTimeout(10000);
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(`${base}/tests/fixtures/collaboration-conversation-ui.html?${query}`);
  await page.locator('.conversation-members-trigger:not(:disabled)').waitFor();
  return page;
}
async function create(page) { await trigger(page).click(); await newItem(page).click(); }
async function history(page) {
  await trigger(page).click();
  await historyItem(page).click();
  return page.getByRole('dialog', { name: '历史会话', exact: true });
}
try {
  for (const theme of ['dark', 'light']) for (const width of [780, 320]) {
    const page = await fresh(`theme=${theme}`, width);
    await page.waitForFunction(() => document.querySelector('.conversation-transcript').textContent.includes('拆解方案'));
    const before = await page.evaluate(() => structuredClone(window.conversationMock.chats.A));
    await editor(page).fill('旧会话草稿');
    await page.getByRole('tab', { name: '任务执行', exact: true }).click();
    await trigger(page).click();
    assert.deepEqual(await page.getByRole('menuitem').allTextContents(), ['新建会话', '重命名会话', '历史会话', '导出会话', '清空讨论记录', '删除会话']);
    assert.equal(await page.getByRole('separator').count(), 0);
    await page.waitForFunction(() => document.activeElement?.getAttribute('role') === 'menuitem' && document.activeElement?.textContent === '新建会话');
    await page.keyboard.press('ArrowDown');
    assert.equal(await page.getByRole('menuitem', { name: '重命名会话' }).evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('ArrowDown');
    assert.equal(await historyItem(page).evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('ArrowDown');
    assert.equal(await exportItem(page).evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('ArrowDown');
    assert.equal(await clearItem(page).evaluate(el => el === document.activeElement), true);
    await page.keyboard.press('Home');
    assert.equal(await newItem(page).evaluate(el => el === document.activeElement), true);
    await page.screenshot({ path: `${out}/menu-${theme}-${width}.png`, fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.keyboard.press('Enter');
    await page.waitForFunction(old => window.conversationMock.chats.A.conversation.id !== old, before.conversation.id);
    await page.waitForFunction(() => document.querySelector('textarea').value === '');
    assert.equal(await page.getByRole('tab', { name: '团队聊天', exact: true }).getAttribute('aria-selected'), 'true');
    assert.equal(await page.locator('.conversation-message').count(), 0);
    const after = await page.evaluate(() => ({ chat: window.conversationMock.chats.A, archived: window.conversationMock.archivedConversations, calls: window.conversationMock.calls }));
    assert.deepEqual(after.archived[0], before, 'old messages and plans are retained');
    assert.equal(after.chat.rounds.length, 0);
    assert.equal(after.chat.executionPlans.length, 0);
    assert.equal(after.calls.filter(c => c.command === 'ma_conversation_clear').length, 0, 'new conversation has its own action');
    assert.equal(after.calls.filter(c => c.command === 'ma_conversation_new').length, 1);
    assert.equal(after.calls.find(c => c.command === 'ma_conversation_new').args.input.expectedConversationId, before.conversation.id);
    await trigger(page).click();
    assert.equal(await newItem(page).isEnabled(), true, 'empty conversation can still start a new one');
    assert.equal(await exportItem(page).isDisabled(), true);
    assert.equal(await clearItem(page).isDisabled(), true);
    await page.keyboard.press('Escape');
    await page.screenshot({ path: `${out}/new-${theme}-${width}.png`, fullPage: true });
    await editor(page).fill('新会话草稿');
    const list = await history(page);
    await list.getByText('空白会话', { exact: true }).waitFor();
    assert.equal(await list.locator('button[aria-current]').count(), 1);
    await page.screenshot({ path: `${out}/history-${theme}-${width}.png`, fullPage: true });
    await list.locator('.conversation-history-list button:not([aria-current])').click();
    await page.locator('.conversation-transcript').getByText(/拆解方案/).waitFor();
    assert.equal(await editor(page).inputValue(), '旧会话草稿');
    await (await history(page)).getByRole('button', { name: /空白会话/ }).click();
    await list.waitFor({ state: 'detached' });
    assert.equal(await page.locator('.conversation-message').count(), 0);
    assert.equal(await editor(page).inputValue(), '新会话草稿');
    assert.equal(await page.evaluate(() => window.conversationMock.calls.filter(c => c.command === 'ma_conversation_switch').length), 2);
    await page.close();
  }
  for (const width of [320, 780]) {
    const page = await fresh('', width);
    const switcher = page.locator('.conversation-switch-trigger');
    const rows = page.locator('.conversation-switch-row');
    const operation = name => page.getByRole('menuitem', { name, exact: true });
    const rename = async (title) => {
      const dialog = page.getByRole('dialog', { name: '重命名会话', exact: true });
      await dialog.getByLabel('会话名称').fill(title);
      await dialog.getByRole('button', { name: '保存', exact: true }).click();
      await dialog.waitFor({ state: 'hidden' });
    };
    const count = () => page.locator('.conversation-target').innerText();
    await switcher.waitFor();
    const currentId = await page.evaluate(() => window.conversationMock.chats.A.conversation.id);
    await page.locator('.conversation-members-trigger').click();
    await page.getByRole('checkbox', { name: 'Claude Code', exact: true }).uncheck();
    await page.keyboard.press('Escape');
    const firstCount = await count();
    assert.match(firstCount, /已选/);
    await page.reload();
    await switcher.waitFor();
    await page.waitForFunction(expected => document.querySelector('.conversation-target')?.innerText === expected, firstCount);
    await trigger(page).click();
    await operation('重命名会话').click();
    await rename('界面讨论');
    await create(page);
    await page.waitForFunction(() => document.querySelector('.conversation-switch-trigger')?.textContent === '空白会话');
    assert.notEqual(await count(), firstCount);
    await page.locator('.conversation-target').click();
    await page.getByRole('button', { name: '取消全选', exact: true }).click();
    await page.keyboard.press('Escape');
    assert.match(await count(), /已选 0 位/);
    await switcher.click();
    await rows.filter({ hasText: '界面讨论' }).waitFor();
    assert.match(await rows.filter({ hasText: '空白会话' }).innerText(), /已选 0 位/);
    await page.getByRole('button', { name: '界面讨论的会话操作' }).click();
    assert.deepEqual(await page.getByRole('menuitem').allTextContents(), ['重命名会话']);
    await page.screenshot({ path: `${out}/switcher-${width}.png` });
    await operation('重命名会话').click();
    await rename('联调记录');
    assert.match(await switcher.innerText(), /空白会话/);
    assert.equal(await page.evaluate(() => window.conversationMock.calls.filter(c => c.command === 'ma_conversation_switch').length), 0);
    await switcher.click();
    await rows.filter({ hasText: '联调记录' }).click();
    await page.getByRole('button', { name: '切换会话：联调记录' }).waitFor();
    assert.equal(await count(), firstCount);
    await switcher.click();
    await rows.filter({ hasText: '空白会话' }).click();
    await page.getByRole('button', { name: '切换会话：空白会话' }).waitFor();
    assert.match(await count(), /已选 0 位/);
    await trigger(page).click(); await operation('重命名会话').click(); await rename('待删除的会话');
    const openDelete = async () => {
      await trigger(page).click();
      await operation('删除会话').click();
      return page.getByRole('dialog', { name: '删除会话', exact: true });
    };
    const dialog = await openDelete();
    assert.match(await dialog.innerText(), /待删除的会话/);
    assert.equal(await dialog.getByRole('button', { name: '取消' }).evaluate(el => el === document.activeElement), true);
    await dialog.getByRole('button', { name: '取消' }).click();
    assert.equal(await page.evaluate(() => window.conversationMock.calls.filter(c => c.command === 'ma_conversation_delete').length), 0);
    await (await openDelete()).getByRole('button', { name: '删除会话', exact: true }).click();
    await dialog.waitFor({ state: 'hidden' });
    await switcher.click();
    await rows.filter({ hasText: '联调记录' }).waitFor();
    assert.equal(await rows.filter({ hasText: '待删除的会话' }).count(), 0);
    const ids = await page.evaluate(() => window.conversationMock.archivedConversations.map(chat => chat.conversation.id));
    assert.deepEqual(ids, [currentId]);
    await page.close();
  }
  for (const scenario of ['success', 'cancel', 'failure']) {
    const page = await fresh(`export=${scenario}`);
    await page.locator('.conversation-transcript').getByText(/拆解方案/).waitFor();
    await editor(page).fill('保留这个草稿');
    const before = await page.evaluate(() => structuredClone(window.conversationMock.chats.A));
    await trigger(page).click();
    await exportItem(page).click();
    await page.waitForFunction(() => window.conversationMock.calls.some(call => call.command === 'ma_conversation_export'));
    assert.deepEqual(await page.evaluate(() => window.conversationMock.calls.find(call => call.command === 'ma_conversation_export').args),
      { projectId: 'A', conversationId: before.conversation.id });
    if (scenario === 'success') await page.getByRole('status').filter({ hasText: '已导出：团队会话-测试.md' }).waitFor();
    else if (scenario === 'failure') await page.getByRole('alert').filter({ hasText: '保存目录无写入权限' }).waitFor();
    else {
      assert.equal(await page.locator('.conversation-export-status').count(), 0);
      assert.equal(await page.getByRole('alert').filter({ hasText: '导出会话失败' }).count(), 0);
    }
    assert.equal(await editor(page).inputValue(), '保留这个草稿');
    assert.deepEqual(await page.evaluate(() => window.conversationMock.chats.A), before);
    await page.close();
  }
  const legacy = await fresh('legacy-history=1');
  await create(legacy);
  await legacy.locator('.conversation-message').first().waitFor({ state: 'detached' });
  const legacyList = await history(legacy);
  const legacyGroup = legacyList.locator('.conversation-legacy-history');
  await legacyGroup.locator('summary').click();
  assert.equal(await legacyGroup.locator('p').isVisible(), true);
  await legacyGroup.getByRole('button').click();
  await legacy.locator('.conversation-transcript').getByText(/拆解方案/).waitFor();
  await legacy.close();
  const running = await fresh('running=1'); await trigger(running).click(); assert.equal(await newItem(running).isDisabled(), true); await running.close();
  const pending = await fresh('fail=send-before-save');
  await editor(pending).fill('未确认的发送'); await editor(pending).press('Enter');
  await pending.getByText('核对并重试', { exact: true }).waitFor(); await trigger(pending).click();
  assert.equal(await newItem(pending).isDisabled(), true); await pending.close();
  const failure = await fresh();
  await editor(failure).fill('失败时保留草稿');
  await failure.evaluate(() => { window.conversationMock.failNew = true; });
  await create(failure);
  await failure.getByRole('alert').filter({ hasText: '新建会话失败' }).waitFor();
  assert.equal(await editor(failure).inputValue(), '失败时保留草稿');
  assert.equal(await failure.evaluate(() => window.conversationMock.chats.A.conversation.id), 'conversation-A');
  await failure.evaluate(() => { window.conversationMock.failNew = false; }); await create(failure);
  await failure.waitForFunction(() => document.querySelector('textarea').value === ''); await failure.close();
  const held = await fresh();
  await editor(held).fill('旧草稿');
  await held.evaluate(() => { window.conversationMock.holdNew = true; });
  await trigger(held).click();
  await newItem(held).evaluate(el => { el.click(); el.click(); });
  assert.equal(await held.evaluate(() => window.conversationMock.calls.filter(c => c.command === 'ma_conversation_new').length), 1);
  await editor(held).fill('请求期间的新草稿');
  await held.evaluate(() => {
    const mock = window.conversationMock, chat = mock.chats.A;
    chat.conversation.id = 'new-held-conversation'; chat.messages = []; chat.rounds = []; chat.executionPlans = [];
    mock.release('ma_conversation_new', structuredClone(chat));
  });
  await held.waitForFunction(() => !document.querySelector('[aria-label="讨论记录操作"]').disabled);
  assert.equal(await editor(held).inputValue(), '请求期间的新草稿'); await held.close();
  assert.deepEqual(errors, []);
  console.log('PASS team conversation: switcher, independent selections after reload, both rename menus, confirmed deletion, fresh context, history/keyboard, busy guards, draft and failure recovery; dark/light/320px.');
} finally { await browser.close(); }
