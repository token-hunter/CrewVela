import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { spawn } from 'node:child_process';
import { chromium } from 'playwright';
const server=spawn(process.execPath,['node_modules/vite/bin/vite.js','--host','127.0.0.1','--port','1495','--strictPort'],{stdio:'pipe'});
await new Promise((resolve,reject)=>{server.stdout.on('data',d=>{if(d.toString().includes('1495'))resolve()});server.on('error',reject);server.on('exit',code=>reject(Error(`vite exited ${code}`)))});
const browser=await chromium.launch({channel:'chrome',headless:true});
try {
 const page=await browser.newPage({viewport:{width:1280,height:850}});
 page.setDefaultTimeout(15000);
 const url='http://127.0.0.1:1495/tests/fixtures/app-session-async-ui.html?handoff-recovery=1';
 await page.goto(url);
 const reminder=page.locator('.session-switch-recovery');
 await reminder.waitFor();
 assert.match(await reminder.innerText(),/接力目标已不存在/);
 await page.getByRole('button',{name:'工作区 B',exact:true}).click();
 assert.equal(await reminder.count(),0,'no reminder in unrelated empty workspace');
 await page.getByRole('button',{name:'工作区 A',exact:true}).click();
 await reminder.waitFor();
 mkdirSync('output/playwright',{recursive:true});
 await page.screenshot({path:'output/playwright/stale-handoff-before.png',fullPage:true});
 await page.evaluate(()=>window.appSessionMock.rejectSwitchDismiss=true);
 await reminder.getByRole('button',{name:'结束接力',exact:true}).click();
 await page.getByText(/结束接力失败.*fixture dismiss failed/).waitFor();
 assert.equal(await reminder.isVisible(),true,'failed save keeps reminder actionable');
 await page.evaluate(()=>window.appSessionMock.rejectSwitchDismiss=false);
 mkdirSync('output/playwright',{recursive:true});
 await page.screenshot({path:'output/playwright/stale-handoff-reminder.png',fullPage:true});
 await reminder.getByRole('button',{name:'结束接力',exact:true}).click();
 await reminder.waitFor({state:'detached'});
 await page.waitForTimeout(2200);
 assert.equal(await reminder.count(),0,'poll does not revive ended reminder');
 assert.deepEqual(await page.evaluate(()=>window.appSessionMock.calls),[],'ending reminder does not resume sessions');
 assert.deepEqual(await page.evaluate(()=>window.appSessionMock.switchCommands),['session_switch_dismiss_recovery','session_switch_dismiss_recovery']);
 await page.reload();
 await page.getByRole('button',{name:'工作区 A',exact:true}).waitFor();
 await page.waitForTimeout(2200);
 assert.equal(await reminder.count(),0,'reload keeps reminder ended');
 assert.equal(await page.evaluate(()=>window.appSessionMock.switchRecords[0].state),'queued','historical handoff state retained');
 assert.equal(await page.evaluate(()=>window.appSessionMock.switchRecords[0].context),'fixture history retained');
 process.env.CREWVELA_UI_URL='http://127.0.0.1:1495';
 await import('./appSessionAsync.ui.mjs');
 console.log('PASS: owning workspace only, explicit stale status, save failure retention, dismiss persistence, poll/reload and no session restoration');
}finally{await browser.close();server.kill()}
