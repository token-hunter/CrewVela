import assert from "node:assert/strict";
import { chromium } from "playwright";
import { tmpdir } from "node:os";
import { join } from "node:path";
const browser = await chromium.launch({channel:"chrome",headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[]; page.on("pageerror",error=>errors.push(error.message));
try {
  await page.goto((process.env.CREWVELA_UI_URL || "http://127.0.0.1:1420")+"/tests/fixtures/plugin-market-ui.html?official=1");
  await page.getByRole("button",{name:"高级",exact:true}).click();
  await page.getByRole("button",{name:"接入 OpenAI 官方候选",exact:true}).click();
  const curation=page.getByRole("dialog",{name:"挑选精选插件"});
  await curation.locator(".pm-candidate-card").first().waitFor();
  assert.equal(await curation.locator(".pm-candidate-card").count(),3);
  assert.equal(await curation.getByRole("checkbox",{checked:true}).count(),0);
  assert.match(await curation.innerText(),/待授权 · 仅展示/);
  assert.match(await curation.innerText(),/Browser、ImageGen、Sites/);
  assert.equal(await page.evaluate(()=>window.__pluginCalls.filter(call=>call.cmd==="plugin_market_install").length),0);
  await curation.getByRole("checkbox",{name:"精选 Remotion（openai-curated）"}).check();
  await curation.getByRole("checkbox",{name:"精选 Product Design（openai-curated）"}).check();
  await page.screenshot({path:join(tmpdir(),"crewvela-official-candidates.png"),fullPage:true});
  await curation.getByRole("button",{name:"保存精选",exact:true}).click();
  await page.locator(".pm-directory-row").first().waitFor();
  assert.equal(await page.locator(".pm-directory-row").count(),2);
  await page.getByRole("combobox",{name:"适用 Agent",exact:true}).selectOption("claude_code");
  assert.equal(await page.locator(".pm-directory-row").count(),0);
  await page.getByRole("combobox",{name:"适用 Agent",exact:true}).selectOption("codex");
  assert.equal(await page.locator(".pm-directory-row").count(),2);
  await page.locator(".pm-directory-row").filter({hasText:"Product Design"}).click();
  const dialog=page.getByRole("region",{name:"插件详情与安装"});
  assert.equal(await dialog.getByRole("radio").count(),1);
  assert.ok(await dialog.getByRole("radio",{name:"Codex 原生插件 · 全局"}).isChecked());
  assert.ok(await dialog.locator(".pm-agent-options label").filter({hasText:/^Claude Code/}).getByRole("checkbox").isDisabled());
  assert.ok(await dialog.getByRole("combobox",{name:"安装作用域"}).isDisabled());
  await dialog.getByText("查看依赖与包说明",{exact:true}).click();
  assert.match(await dialog.innerText(),/Browser、ImageGen、Sites/);
  assert.match(await dialog.innerText(),/专有许可/);
  assert.match(await dialog.locator(".pm-source-full").innerText(), /openai\/plugins \/ plugins\/product-design/);
  assert.ok(!(await dialog.locator(".pm-source").innerText()).includes("anthropics"));
  await dialog.getByRole("checkbox",{name:"我已审阅并信任此来源，允许安装插件与附带代码。"}).check();
  await dialog.getByRole("button",{name:"安装到 1 个 Agent"}).click();
  await dialog.getByRole("status").waitFor();
  const input=await page.evaluate(()=>window.__pluginCalls.find(call=>call.cmd==="plugin_market_install").args.input);
  assert.equal(input.mode,"native_codex"); assert.equal(input.scope,"global");
  assert.deepEqual(input.runtimes,["codex"]);
  assert.match(await dialog.getByRole("status").innerText(),/安装记录已核验/);
  await page.screenshot({path:join(tmpdir(),"crewvela-official-product-design.png"),fullPage:true});
  await page.setViewportSize({width:600,height:1000});
  await page.getByRole("button",{name:"管理精选",exact:true}).click();
  await curation.locator(".pm-candidate-card").first().waitFor();
  assert.ok(!(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)));
  await page.screenshot({path:join(tmpdir(),"crewvela-official-narrow.png"),fullPage:true});
  assert.deepEqual(errors,[]);
  console.log("PASS: 官方候选显式接入、无默认精选/安装、连接器待授权、Codex 专属筛选/安装契约、Product Design 宿主/许可边界、窄屏");
} finally { await browser.close(); }
