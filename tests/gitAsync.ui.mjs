import assert from "node:assert/strict";
import { chromium } from "playwright";
import { mkdirSync } from "node:fs";

const browser = await chromium.launch({ channel: "chrome", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1100, height: 850 } });
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  const url = new URL("/tests/fixtures/git-async-ui.html", process.env.CREWVELA_UI_URL || "http://127.0.0.1:1432");
  const release = (command, error, cwd) => page.evaluate(args => window.gitMock.release(...args), [command, error, cwd]);
  await page.goto(url.href);
  const workspace = page.getByRole("combobox", { name: "选择 Git 工作区" });
  assert.equal(await workspace.locator("option").count(), 2, "POSIX case-sensitive paths remain distinct");
  const unstage = page.getByTitle("取消暂存", { exact: true });
  await unstage.waitFor();
  await page.getByPlaceholder("提交信息", { exact: true }).fill("Repo A draft");
  await unstage.evaluate(button => { button.click(); button.click(); });
  assert.equal(await page.evaluate(() => window.gitMock.calls.filter(item => item.command === "git_unstage").length), 1);
  await workspace.selectOption("project:b");
  await page.getByText("/repo.txt", { exact: true }).first().waitFor();
  await release("git_branches", undefined, "/repo");
  await release("git_branches", undefined, "/Repo");
  await release("git_unstage");
  assert.equal(await page.getByText("old-receipt.txt", { exact: true }).count(), 0);
  await page.locator(".git-source-sidebar-overflow summary").click();
  await page.getByRole("button", { name: "Merge…", exact: true }).first().click();
  assert.equal(await page.getByRole("dialog").locator("select").inputValue(), "/repo-branch");
  await page.getByRole("button", { name: "关闭合并分支" }).click();
  await page.locator(".git-source-sidebar-overflow summary").click();
  const draft = page.getByPlaceholder("提交信息", { exact: true });
  await draft.fill("first commit");
  const commit = page.locator(".git-source-sidebar-primary > button");
  await commit.evaluate(button => { button.click(); button.click(); });
  await draft.fill("next draft");
  await release("git_commit");
  assert.equal(await draft.inputValue(), "next draft");
  assert.equal(await page.evaluate(() => window.gitMock.calls.filter(item => item.command === "git_commit").length), 1);
  await page.getByRole("button", { name: "AI 生成提交信息", exact: true }).click();
  await draft.fill("manual revision");
  await release("git_generate_commit_message");
  assert.equal(await draft.inputValue(), "manual revision");
  await commit.click();
  await release("git_commit", "commit failed");
  await page.getByText(/commit failed/).waitFor();
  assert.equal(await draft.inputValue(), "manual revision");
  await commit.click();
  await release("git_commit");
  await page.waitForFunction(() => document.querySelector("textarea").value === "");
  await draft.fill("Repo B draft");
  await workspace.selectOption("project:a");
  assert.equal(await draft.inputValue(), "Repo A draft");
  await workspace.selectOption("project:b");
  assert.equal(await draft.inputValue(), "Repo B draft");
  mkdirSync("output/playwright", { recursive: true });
  await page.screenshot({ path: "output/playwright/git-source-async.png", fullPage: true });

  await page.goto(new URL("?mode=settings", url).href);
  const save = page.getByRole("button", { name: "保存设置", exact: true });
  assert.equal(await save.isDisabled(), true);
  await release("git_settings_get", "settings read failed");
  assert.equal(await save.isDisabled(), true);
  await page.getByRole("button", { name: "重新读取" }).click();
  await release("git_settings_get");
  const prefix = page.getByPlaceholder("crewvela/");
  await prefix.fill("custom/");
  await save.evaluate(button => { button.click(); button.click(); });
  assert.equal(await prefix.isDisabled(), true);
  assert.equal(await page.evaluate(() => window.gitMock.calls.filter(item => item.command === "git_settings_save").length), 1);
  await release("git_settings_save", "settings save failed");
  await page.getByText(/settings save failed/).waitFor();
  assert.equal(await prefix.inputValue(), "custom/");
  await save.click();
  await release("git_settings_save");
  await page.getByText("Git 设置已保存", { exact: true }).waitFor();
  mkdirSync("output/playwright", { recursive: true });
  await page.screenshot({ path: "output/playwright/git-async.png", fullPage: true });
  assert.deepEqual(errors, []);
  console.log("Git UI: workspace isolation, branch ordering, duplicate actions, draft preservation, failure/retry and settings passed");
} finally { await browser.close(); }
