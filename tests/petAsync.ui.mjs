import assert from "node:assert/strict";
import { chromium } from "playwright";
import { mkdirSync } from "node:fs";
const browser = await chromium.launch({ channel: "chrome", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1100, height: 1000 } });
  page.setDefaultTimeout(10000); page.on("dialog", dialog => dialog.accept());
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  const url = new URL("/tests/fixtures/pet-async-ui.html", process.env.CREWVELA_UI_URL || "http://127.0.0.1:1432");
  const state = id => page.locator(id).textContent().then(JSON.parse);
  await page.goto(url.href);
  const input = page.locator(".pet-file-input");
  const file = { name: "new-pet.png", mimeType: "image/png", buffer: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=", "base64") };
  await input.setInputFiles(file);
  await page.waitForFunction(() => window.petMock.reads.length === 1);
  await input.setInputFiles({ ...file, name: "duplicate-pet.png" });
  assert.equal(await page.evaluate(() => window.petMock.reads.length), 1);
  await page.getByRole("button", { name: "删除 Old pet", exact: true }).click();
  await page.locator(".pet-size-control input").press("End");
  await page.locator(".pet-choice-main").nth(1).click();
  await page.getByRole("switch", { name: "显示桌宠", exact: true }).uncheck();
  await page.evaluate(() => window.petMock.readPet());
  await page.waitForFunction(() => JSON.parse(document.querySelector("#pet-state").textContent).customPets.some(item => item.name === "new-pet"));
  const saved = await state("#pet-state");
  assert.equal(saved.size, 192); assert.equal(saved.enabled, false); assert.equal(saved.selectedId, "orange-sleepy");
  assert.deepEqual(saved.customPets.map(item => item.name), ["new-pet"]);
  await input.setInputFiles({ ...file, name: "normal-pet.png" });
  await page.evaluate(() => window.petMock.readPet());
  await page.waitForFunction(() => JSON.parse(document.querySelector("#pet-state").textContent).customPets.length === 2);
  assert.equal((await state("#pet-state")).enabled, true);
  assert.equal((await state("#pet-state")).customPets.at(-1).id, (await state("#pet-state")).selectedId);
  await page.screenshot({ path: "output/playwright/pet-import-final.png", fullPage: true });
  await input.setInputFiles({ ...file, name: "closed-pet.png" });
  await page.getByRole("button", { name: "关闭桌宠面板", exact: true }).click();
  await page.evaluate(() => window.petMock.readPet());
  await page.waitForFunction(() => window.petMock.completedReads === 3);
  assert.equal((await state("#pet-state")).customPets.length, 2);
  assert.deepEqual(errors, []);
  mkdirSync("output/playwright", { recursive: true });
  await page.screenshot({ path: "output/playwright/pet-async.png", fullPage: true });
  console.log("PASS: pet import excludes duplicates, preserves concurrent edits/deletions, normally selects imported pet and ignores unmounted completion");
} finally { await browser.close(); }
