import assert from "node:assert/strict";
import { chromium } from "playwright";
const browser=await chromium.launch({channel:"chrome",headless:true});
try {
  const page=await browser.newPage({viewport:{width:1100,height:900}});
  page.setDefaultTimeout(10000);
  const errors=[];page.on("pageerror",e=>errors.push(e.message));
  const base=process.env.CREWVELA_UI_URL || "http://127.0.0.1:1436";
  const url=`${base}/tests/fixtures/collaboration-records-ui.html`;
  await page.goto(url);
  const records=page.getByRole("region",{name:"协作记录",exact:true});
  await records.getByText("A投递正文",{exact:true}).waitFor();
  assert.equal(await records.getByText("B投递正文",{exact:true}).count(),0);
  assert.equal(await records.getByText("foreign投递正文",{exact:true}).count(),0);
  await page.getByRole("searchbox",{name:"搜索记录"}).fill("第二行正文");
  assert.equal(await records.locator("article").count(),1);
  assert.equal(await records.locator("pre").innerText(),"A项目完整消息\n第二行正文");
  await records.locator("button[aria-expanded]").click();
  assert.equal(await records.locator("pre").count(),0);
  await page.getByRole("combobox",{name:"记录类型"}).selectOption("运行");
  await records.getByText("没有符合条件的记录").waitFor();
  await page.getByRole("searchbox",{name:"搜索记录"}).fill("");
  await page.getByRole("combobox",{name:"记录类型"}).selectOption("全部");
  await page.evaluate(()=>{window.recordMock.failDelivery=true;});
  await records.getByRole("alert").filter({hasText:"fixture delivery failure"}).waitFor();
  assert.equal(await records.locator("article").count(),3,"a projection failure must not hide the loaded history");
  await page.evaluate(()=>{window.recordMock.failDelivery=false;});
  await records.getByRole("button",{name:"重试",exact:true}).click();
  await records.getByRole("alert").waitFor({state:"detached"});
  await page.evaluate(()=>{window.recordMock.holdDelivery=true;});
  await page.waitForFunction(()=>window.recordMock.pending.length===1);
  await page.getByRole("combobox",{name:"当前项目"}).selectOption("B");
  await page.waitForFunction(()=>window.recordMock.pending.length===2);
  assert.doesNotMatch(await records.innerText(),/A项目|A投递/);
  await page.evaluate(()=>window.recordMock.resolveDelivery([{id:"stale",at:Date.now(),fromSessionId:null,toSessionId:"A-session",body:"旧项目延迟正文",kind:"direct"}]));
  assert.doesNotMatch(await records.innerText(),/旧项目延迟正文/);
  await page.evaluate(()=>window.recordMock.resolveDelivery([{id:"B-live",at:Date.now(),fromSessionId:null,toSessionId:"B-session",body:"B实时投递",kind:"direct"}]));
  await records.getByText("B实时投递",{exact:true}).waitFor();
  await page.goto(`${url}?mode=workspace`);
  await page.locator(".ma-workspace-body").waitFor();
  assert.equal(await page.locator(".ma-collaboration-rail").count(),0);
  assert.equal(await page.evaluate(()=>window.recordMock.calls.some(item=>item.command==="list_delivery_records")),false);
  const geometry=await page.locator(".ma-workspace-body").evaluate(el=>({body:el.clientWidth,terminal:el.firstElementChild.getBoundingClientRect().width}));
  assert.ok(Math.abs(geometry.body-geometry.terminal)<2,"terminal area should use the former rail width");
  assert.deepEqual(errors,[]);
  console.log("PASS: all records, full body/search/type/expand, delivery failure retry, project isolation and full-width rail-free workspace");
}finally{await browser.close();}
