import assert from "node:assert/strict";
import { mkdirSync } from "node:fs";
import { chromium } from "playwright";

const base = process.env.CREWVELA_UI_URL || "http://127.0.0.1:1420";
const output = ".scratch/shared-memory-quick-setup/ui";
mkdirSync(output, { recursive: true });
const browser = await chromium.launch({ channel: "chrome", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.clock.install();
  await page.goto(`${base}/tests/fixtures/shared-memory-quick-setup.html`);
  await page.getByRole("button", { name: "开始配置", exact: true }).waitFor();
  assert.equal(await page.evaluate(() => window.__quickCalls.filter(x => x.command.startsWith("ai_memory_quick")).length), 0);
  await page.getByRole("button", { name: "开始配置", exact: true }).click();
  await page.getByRole("button", { name: "选择启用项目" }).click();
  await page.getByText("下载较慢？使用本地官方安装包", { exact: true }).click();
  await page.getByRole("button", { name: "选择本地 ZIP" }).click();
  await page.evaluate(() => { window.__quickHold = true; });
  await page.getByRole("button", { name: "安装并启用", exact: true }).click();
  await page.getByRole("button", { name: "正在启用…", exact: true }).waitFor();
  assert(await page.locator(".sm-service .sm-actions button").evaluateAll(buttons => buttons.length > 0 && buttons.every(button => button.disabled)));
  await page.evaluate(() => { window.__quickHold = false; window.__quickRelease(); });
  await page.waitForFunction(() => window.__quickJob);
  const request = await page.evaluate(() => window.__quickCalls.find(x => x.command === "ai_memory_quick_start").args.request);
  assert.deepEqual(request.agents, ["claude-code", "codex"]);
  assert.match(request.localArchive, /\.zip$/);
  assert.equal(await page.evaluate(() => window.__quickCalls.filter(x => x.command === "ai_memory_quick_start").length), 1);
  await page.getByRole("button", { name: "接入配置", exact: true }).click();
  assert(await page.getByRole("button", { name: "安装钩子", exact: true }).isDisabled());
  await page.evaluate(() => { window.__quickJob.state = "failed"; window.__quickJob.steps[0].state = "failed"; window.__quickJob.steps[0].detail = "模拟校验失败，原配置保持不变"; });
  await page.clock.runFor(1000);
  await page.getByRole("button", { name: "概览", exact: true }).click();
  await page.getByText("模拟校验失败，原配置保持不变", { exact: true }).waitFor();
  await page.getByRole("button", { name: "重试启用", exact: true }).click();
  await page.waitForFunction(() => window.__quickJob?.id === "fixture-2");
  await page.evaluate(() => { window.__quickPollError = true; });
  await page.clock.runFor(1200);
  await page.getByRole("alert").filter({ hasText: "读取进度失败" }).waitFor();
  assert(await page.getByRole("button", { name: "正在启用…", exact: true }).isDisabled());
  await page.evaluate(() => { window.__quickPollError = false; window.__quickHealthy = true; window.__quickJob.state = "awaiting-session"; window.__quickJob.steps.forEach(step => { step.state = "done"; step.detail = "配置检查通过"; }); });
  await page.clock.runFor(1200);
  await page.getByText("配置完成，待新会话验证", { exact: true }).waitFor();
  assert.equal(await page.getByRole("alert").count(), 0);
  await page.screenshot({ path: `${output}/desktop.png`, fullPage: true });
  for (const theme of ["dark", "light"]) {
    await page.evaluate(theme => document.documentElement.dataset.theme = theme, theme);
    await page.setViewportSize({ width: 600, height: 1000 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: `${output}/${theme}-600.png`, fullPage: true });
  }
  await page.getByRole("button", { name: "前往接入检查", exact: true }).click();
  await page.locator(".sm-setup-v2").getByText("C:/projects/demo", { exact: true }).waitFor();
  assert(await page.getByRole("button", { name: "检查接入", exact: true }).isEnabled());
  await page.reload();
  await page.evaluate(() => { window.__quickInfo.agents[1].installed = false; });
  await page.getByRole("button", { name: "开始配置", exact: true }).click();
  assert(await page.getByRole("checkbox", { name: /Codex/ }).isDisabled());
  assert(await page.getByRole("checkbox", { name: /Claude Code/ }).isChecked());
  await page.getByRole("button", { name: "选择启用项目" }).click();
  await page.getByRole("button", { name: "安装并启用", exact: true }).click();
  await page.waitForFunction(() => window.__quickJob);
  await page.evaluate(() => window.unmountQuickFixture());
  const calls = await page.evaluate(() => window.__quickCalls.length);
  await page.clock.runFor(5000);
  assert.equal(await page.evaluate(() => window.__quickCalls.length), calls);
  await page.reload();
  await page.evaluate(() => { window.__quickJob = { id: "restored", projectDir: "C:/old", agents: ["codex"], state: "failed", steps: [{ id: "install", label: "安装兼容版本并校验", state: "failed", detail: "上次运行中断" }] }; });
  await page.getByRole("button", { name: "开始配置", exact: true }).click();
  await page.getByText("上次运行中断", { exact: true }).waitFor();
  await page.reload();
  await page.evaluate(() => { window.__quickInfo.supported = false; });
  await page.getByRole("button", { name: "开始配置", exact: true }).click();
  await page.getByText("当前平台暂不支持快速启用，请使用接入配置中的手动操作。", { exact: true }).waitFor();
  assert(await page.getByRole("button", { name: "安装并启用", exact: true }).isDisabled());
  assert.deepEqual(errors, []);
  console.log("PASS: lazy loading, selected agents/project/ZIP, busy guards, tab switching, failure/retry, polling recovery, pending capture, themes/600px, missing CLI, restore and unmount");
} finally { await browser.close(); }
