import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {mkdirSync} from 'node:fs';
const base=process.env.CREWVELA_UI_URL||'http://127.0.0.1:1447';
const output='.scratch/conversation-approval-recovery';mkdirSync(output,{recursive:true});
const browser=await chromium.launch({channel:'chrome'});
const errors=[];
try {
 const page=await browser.newPage({viewport:{width:1000,height:1100}});page.on('pageerror',e=>errors.push(e.message));
 await page.goto(`${base}/tests/fixtures/collaboration-conversation-ui.html?activity=1&approval=1`);
 const card=page.getByRole('region',{name:'工具授权请求'});
 await card.getByText('Claude 请求运行命令：npm test',{exact:true}).waitFor();
 await page.locator('.conversation-progress').getByText('Claude · 等待工具授权',{exact:true}).waitFor();
 assert.equal(await page.locator('[data-message-id="a2"] .conversation-approval').count(),0);
 await card.getByText('查看请求内容',{exact:true}).click();
 await card.getByText('{"command":"npm test"}',{exact:true}).waitFor();
 await card.getByRole('button',{name:'查看原会话',exact:true}).click();
 assert.equal(await page.evaluate(()=>window.conversationMock.calls.filter(c=>c.command==='fixture_open_session').at(-1).args.sessionId),'session-claude');
 await page.evaluate(()=>{window.conversationMock.failPermission=true;});
 await card.getByRole('button',{name:'允许本次操作'}).click();
 await card.getByRole('alert').getByText(/批准未保存/).waitFor();
 assert.equal(await card.getByRole('button',{name:'允许本次操作'}).isEnabled(),true);
 await page.evaluate(()=>{window.conversationMock.failPermission=false;});
 await card.getByRole('button',{name:'允许本次操作'}).click();
 await card.waitFor({state:'detached'});
 const calls=await page.evaluate(()=>window.conversationMock.calls);
 assert.equal(calls.filter(c=>c.command==='ma_resolve_intervention').length,2);
 assert.ok(calls.filter(c=>c.command==='ma_resolve_intervention').every(c=>c.args.input.interventionId==='permission-current'));
 assert.equal(calls.filter(c=>c.command==='ma_start_project').length,0);
 await page.reload();await card.waitFor();
 await page.evaluate(()=>{window.conversationMock.stalePermission=true;});
 await card.getByRole('button',{name:'允许本次操作'}).click();
 await card.getByRole('alert').getByText(/请求已变化/).waitFor();
 assert.equal(await page.evaluate(()=>window.conversationMock.calls.filter(c=>c.command==='ma_resolve_intervention').length),0);
 await page.setViewportSize({width:390,height:844});
 await card.scrollIntoViewIfNeeded();
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:`${output}/approval-narrow.png`});
 await page.setViewportSize({width:1000,height:1100});await card.scrollIntoViewIfNeeded();
 await page.screenshot({path:`${output}/approval-desktop.png`});
 await card.getByRole('button',{name:'停止本轮',exact:true}).click();
 assert.equal(await page.evaluate(()=>window.conversationMock.calls.filter(c=>c.command==='ma_conversation_control').at(-1).args.action),'cancel');
 assert.deepEqual(errors,[]);
 console.log('PASS permission UI: exact project/run/task approval, details, original session, visible failure/retry, stale request, stop and narrow layout');
} finally {await browser.close();}
