import assert from "node:assert/strict";
import { mkdirSync } from "node:fs";
import { chromium } from "playwright";

const browser = await chromium.launch({ channel: "chrome", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 780, height: 1000 } });
  page.setDefaultTimeout(10000);
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto(new URL("/tests/fixtures/retained-control-ui.html?mode=member-selection", process.env.CREWVELA_UI_URL || "http://127.0.0.1:1432").href);
  const editor = page.getByPlaceholder("输入指令；使用 @ 或选择目标进入项目协作……");
  const picker = page.getByRole("button", { name: "快捷指令与协作目标", exact: true });
  await editor.fill("互相介绍一下");
  await picker.click();
  const list = page.getByRole("listbox", { name: "具体 Agent", exact: true });
  const members = list.getByRole("option");
  await members.first().waitFor();
  assert.equal(await members.count(), 3, "disabled members and disabled runtimes must be excluded");
  assert.deepEqual(await members.locator("strong").allTextContents(), ["@架构师", "@开发员", "@审查员"]);
  assert.equal(await page.locator(".multi-agent-target-menu").getByText("群组", { exact: true }).count(), 0);
  await members.nth(1).click();
  await members.nth(2).click();
  assert.equal(await list.isVisible(), true, "multi-selection must keep the picker open");
  assert.equal(await list.locator('[aria-selected="true"]').count(), 2);
  assert.equal(await editor.inputValue(), "互相介绍一下 @开发员 @审查员 ");
  await page.getByRole("button", { name: "全选", exact: true }).click();
  assert.equal(await list.locator('[aria-selected="true"]').count(), 3);
  const selected = await editor.inputValue();
  assert.equal(selected.split("@开发员").length - 1, 1, "select all must not duplicate existing mentions");
  assert.doesNotMatch(selected, /@All|@Codex|@ClaudeCode/);
  mkdirSync("output/playwright", { recursive: true });
  await page.screenshot({ path: "output/playwright/explicit-agent-selection-all.png", fullPage: true });
  await page.getByRole("button", { name: "取消全选", exact: true }).click();
  assert.equal(await list.locator('[aria-selected="true"]').count(), 0);
  assert.equal(await editor.inputValue(), "互相介绍一下");
  await members.nth(0).click();
  await members.nth(2).click();
  await members.nth(0).click();
  assert.equal(await list.locator('[aria-selected="true"]').count(), 1);
  await page.getByRole("button", { name: "完成", exact: true }).click();
  assert.equal(await list.count(), 0);
  assert.equal(await editor.evaluate(element => document.activeElement === element), true);
  await editor.press("Control+Enter");
  await page.waitForFunction(() => window.retainedControlMock.calls.some(item => item.command === "ma_send_direct_message"));
  const directCalls = () => page.evaluate(() => window.retainedControlMock.calls.filter(item => item.command === "ma_send_direct_message").map(item => item.args.input));
  const [first] = await directCalls();
  assert.deepEqual(first.targetAgentIds, ["A-reviewer"], "must address the selected reviewer, not an automatic Codex representative");
  assert.deepEqual(first.targetRuntimeKinds, []);
  assert.deepEqual(first.targetSessionIds, []);
  assert.equal(first.projectId, "A");
  await page.locator(".multi-agent-message").filter({ hasText: "fixture direct queued" }).waitFor();

  await editor.fill("@");
  const mention = page.locator(".multi-agent-mention-menu");
  await mention.waitFor();
  assert.deepEqual(await mention.getByRole("option").locator("strong").allTextContents(), ["@架构师", "@开发员", "@审查员"]);
  await page.screenshot({ path: "output/playwright/explicit-agent-mention.png", fullPage: true });
  await mention.getByRole("button", { name: "全选", exact: true }).click();
  assert.equal(await editor.inputValue(), "@架构师 @开发员 @审查员 ", "autocomplete select-all must remove the unfinished @ query");
  await editor.pressSequentially("互相介绍一下");
  await editor.press("Control+Enter");
  await page.waitForFunction(() => window.retainedControlMock.calls.filter(item => item.command === "ma_send_direct_message").length === 2);
  assert.deepEqual((await directCalls())[1].targetAgentIds, ["A-claude", "A-codex", "A-reviewer"]);
  assert.deepEqual((await directCalls())[1].targetRuntimeKinds, []);
  await page.waitForFunction(() => document.querySelector(".multi-agent-composer textarea")?.value === "");
  await editor.fill("@审");
  await mention.getByRole("option").waitFor();
  await editor.press("Enter");
  assert.equal(await editor.inputValue(), "@审查员 ", "keyboard selection must still work");
  await picker.click();
  assert.equal(await list.locator('[aria-selected="true"]').count(), 1);
  await page.getByRole("button", { name: "全选", exact: true }).click();
  await page.getByRole("button", { name: "完成", exact: true }).click();
  await page.evaluate(() => window.retainedControlMock.selectProject("B"));
  await picker.click();
  await page.waitForFunction(() => window.retainedControlMock.calls.some(item => item.command === "ma_snapshot" && item.args.projectId === "B"));
  await page.getByRole("button", { name: "取消全选", exact: true }).click();
  assert.equal(await list.locator('[aria-selected="true"]').count(), 0);
  await page.getByRole("button", { name: "全选", exact: true }).click();
  await page.getByRole("button", { name: "完成", exact: true }).click();
  await editor.pressSequentially("互相介绍一下");
  await editor.press("Control+Enter");
  await page.waitForFunction(() => window.retainedControlMock.calls.filter(item => item.command === "ma_send_direct_message").length === 3);
  const last = (await directCalls())[2];
  assert.equal(last.projectId, "B");
  assert.deepEqual(last.targetAgentIds, ["B-claude", "B-codex", "B-reviewer"]);
  assert.deepEqual(errors, []);
  console.log("PASS: concrete members only, continuous multi-select, select all/clear, keyboard mentions, exact IPC identities and project isolation");
} finally {
  await browser.close();
}
