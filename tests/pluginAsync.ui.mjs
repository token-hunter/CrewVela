import assert from "node:assert/strict";
import { chromium } from "playwright";
const browser = await chromium.launch({ channel: "chrome", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  const release = (cmd, error) => page.evaluate(([cmd, error]) => {
    const index = window.__pluginPending.findIndex(item => item.cmd === cmd);
    if (index < 0) throw Error(`Missing ${cmd}`);
    const item = window.__pluginPending.splice(index, 1)[0];
    if (error) item.reject(Error(error)); else item.resolve();
  }, [cmd, error]);
  await page.goto(new URL("/tests/fixtures/plugin-market-ui.html?delay-load=1", process.env.CREWVELA_UI_URL || "http://127.0.0.1:1432").href);
  await page.getByRole("button", { name: "管理精选", exact: true }).click();
  const curation = page.getByRole("dialog", { name: "挑选精选插件" });
  await curation.locator(".pm-candidate-card").first().waitFor();
  const checked = curation.locator("input:checked");
  while (await checked.count()) await checked.first().uncheck();
  await curation.getByRole("checkbox").first().check();
  await page.evaluate(() => window.__pluginHolds.push("plugin_market_save_selection"));
  const save = curation.getByRole("button", { name: "保存精选", exact: true });
  await save.evaluate(button => { button.click(); button.click(); });
  assert.equal(await page.evaluate(() => window.__pluginCalls.filter(item => item.cmd === "plugin_market_save_selection").length), 1);
  await release("plugin_market_save_selection", "fixture save failed");
  await curation.getByRole("alert").waitFor();
  assert.equal(await curation.locator("input:checked").count(), 1);
  await save.click();
  await release("plugin_market_save_selection");
  await curation.waitFor({ state: "hidden" });
  await release("plugin_market_snapshot");
  await page.waitForFunction(() => document.querySelectorAll(".pm-directory-row").length === 1);
  await page.evaluate(() => { window.__pluginHolds = ["plugin_market_install"]; });
  await page.locator(".pm-directory-row").first().click();
  const detail = page.getByRole("region", { name: "插件详情与安装" });
  await detail.locator(".pm-agent-options input").first().check();
  await detail.locator(".pm-trust input").check();
  const install = detail.getByRole("button", { name: "安装到 1 个 Agent", exact: true });
  await install.evaluate(button => { button.click(); button.click(); });
  assert.equal(await page.evaluate(() => window.__pluginCalls.filter(item => item.cmd === "plugin_market_install").length), 1);
  await release("plugin_market_install", "fixture install failed");
  await detail.getByText(/fixture install failed/).waitFor();
  assert.equal(await detail.locator(".pm-trust input").isChecked(), true);
  await install.click();
  await release("plugin_market_install");
  await detail.getByText(/Skill 已分发到 Claude Code/).waitFor();
  await page.screenshot({ path: "output/playwright/plugin-async.png", fullPage: true });
  assert.deepEqual(errors, []);
  console.log("Plugin UI: stale initial snapshot, duplicate save/install, failure retention and retry passed");
} finally { await browser.close(); }
