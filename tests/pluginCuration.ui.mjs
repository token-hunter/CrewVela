import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const browser = await chromium.launch({channel:'chrome',headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
try {
 await page.goto((process.env.CREWVELA_UI_URL || 'http://127.0.0.1:1420') + '/tests/fixtures/plugin-market-ui.html?curation=1');
 await page.locator('.pm-intro').waitFor();
 assert.equal(await page.locator('.pm-card').count(),0);
 await page.getByRole('button',{name:'挑选精选',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'挑选精选插件'});
 await dialog.locator('.pm-candidate-card').first().waitFor();
 assert.equal(await dialog.locator('.pm-candidate-card').count(),6);
 await dialog.getByRole('checkbox').first().check();
 await dialog.getByRole('button',{name:'取消',exact:true}).click();
 assert.equal(await page.locator('.pm-card').count(),0);
 assert.equal(await page.evaluate(()=>window.__pluginCalls.filter(c=>c.cmd==='plugin_market_save_selection').length),0);
 await page.getByRole('button',{name:'挑选精选',exact:true}).click();
 await dialog.getByRole('checkbox').first().check();
 await dialog.getByRole('textbox',{name:'搜索候选插件'}).fill('PDF');
 await dialog.getByRole('checkbox').check();
 await page.evaluate(()=>window.__curationFailure=true);
 await dialog.getByRole('button',{name:'保存精选',exact:true}).click();
 await dialog.getByRole('alert').waitFor();
 assert.match(await dialog.innerText(),/已选 2/);
 await page.evaluate(()=>window.__curationFailure=false);
 await dialog.getByRole('button',{name:'保存精选',exact:true}).click();
 await dialog.waitFor({state:'hidden'});
 assert.equal(await page.locator('.pm-card').count(),2);
 await page.reload(); await page.locator('.pm-card').first().waitFor();
 assert.equal(await page.locator('.pm-card').count(),2);
 await page.getByRole('button',{name:'挑选精选',exact:true}).click();
 await dialog.locator('.pm-candidate-card').first().waitFor();
 const checked=dialog.locator('input[type=checkbox]:checked');
 while(await checked.count()) await checked.first().uncheck();
 await dialog.getByRole('button',{name:'保存空精选',exact:true}).click();
 await dialog.waitFor({state:'hidden'});
 await page.reload(); await page.locator('.pm-intro').waitFor();
 assert.equal(await page.locator('.pm-card').count(),0);
 await page.getByRole('button',{name:'管理安装',exact:true}).click();
 assert.equal(await page.getByRole('cell',{name:'前端设计',exact:false}).count(),1);
 await page.getByRole('button',{name:'返回精选目录',exact:true}).click();
 await page.evaluate(()=>window.__candidateFailure=true);
 await page.getByRole('button',{name:'挑选精选',exact:true}).click();
 await dialog.getByRole('alert').waitFor();
 assert.ok(await dialog.getByRole('button',{name:'保存空精选',exact:true}).isDisabled());
 await dialog.getByRole('button',{name:'取消',exact:true}).click();
 await page.evaluate(()=>window.__candidateFailure=false);
 await page.getByRole('button',{name:'挑选精选',exact:true}).click();
 await dialog.locator('.pm-candidate-card').first().waitFor();
 await page.screenshot({path:join(tmpdir(),'crewvela-plugin-curation.png'),fullPage:true});
 await page.setViewportSize({width:600,height:1000});
 assert.ok(!(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)));
 assert.deepEqual(errors,[]);
 assert.ok(!(await page.evaluate(()=>window.__pluginCalls.some(c=>['plugin_market_install','plugin_market_remove_target'].includes(c.cmd)))));
 console.log('PASS: 首次空目录、候选取消、跨筛选勾选、失败保留草稿、保存/刷新、空名单、既有安装保留、来源故障拒绝保存、600px');
} finally { await browser.close(); }
