// Against an existing Vite server; the fixture uses mock invoke and no user files.
import assert from "node:assert/strict";
import { chromium } from "playwright";
import { tmpdir } from "node:os";
import { join } from "node:path";
const browser = await chromium.launch({ channel: "chrome", headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on("pageerror", (error) => errors.push(error.message));
try {
  await page.goto((process.env.CREWVELA_UI_URL || "http://127.0.0.1:1420") + "/tests/fixtures/plugin-market-ui.html");
  await page.locator(".pm-directory-row").first().waitFor();
  assert.equal(await page.locator(".pm-directory-row").count(), 16);
  await page.getByRole("combobox", { name: "插件分类", exact: true }).selectOption("设计与创作");
  assert.equal(await page.locator(".pm-directory-row").count(), 6);
  await page.getByRole("combobox", { name: "插件分类", exact: true }).selectOption("全部");
  await page.getByRole("textbox", { name: "搜索插件或使用场景" }).fill("PDF 处理");
  assert.equal(await page.locator(".pm-directory-row").count(), 1);
  await page.getByRole("textbox", { name: "搜索插件或使用场景" }).fill("");
  await page.screenshot({ path: join(tmpdir(), "crewvela-plugin-catalog.png"), fullPage: true });
  await page.locator(".pm-directory-row").first().click();
  const dialog = page.getByRole("region", { name: "插件详情与安装" });
  assert.ok(await dialog.getByRole("button", { name: "安装到 0 个 Agent" }).isDisabled());
  await dialog.locator(".pm-agent-options label").filter({ hasText: "Claude Code" }).getByRole("checkbox").check();
  await dialog.locator(".pm-agent-options label").filter({ hasText: /^Codex/ }).getByRole("checkbox").check();
  assert.ok(await dialog.getByRole("button", { name: "安装到 2 个 Agent" }).isDisabled());
  await dialog.getByText("更多 Agent", { exact: true }).click();
  assert.ok(await dialog.locator(".pm-agent-options label").filter({ hasText: /^ZCode/ }).getByRole("checkbox").isDisabled());
  await dialog.getByRole("combobox", { name: "安装作用域" }).selectOption("project");
  await dialog.locator(".pm-trust input").check();
  assert.ok(await dialog.getByRole("button", { name: "安装到 2 个 Agent" }).isDisabled());
  await dialog.getByRole("combobox", { name: "安装项目" }).selectOption("F:/project/demo");
  await page.screenshot({ path: join(tmpdir(), "crewvela-plugin-detail.png"), fullPage: true });
  await dialog.getByRole("button", { name: "安装到 2 个 Agent" }).click();
  await dialog.getByRole("status").waitFor();
  const input = await page.evaluate(() => window.__pluginCalls.find((call) => call.cmd === "plugin_market_install").args.input);
  assert.deepEqual(input.runtimes, ["claude_code", "codex"]);
  assert.equal(input.projectPath, "F:/project/demo");
  assert.equal(input.scope, "project"); assert.equal(input.trustConfirmed, true); assert.equal(input.mode, "skills");
  await page.getByRole("button", { name: "我的插件", exact: true }).click();
  await page.screenshot({ path: join(tmpdir(), "crewvela-plugin-installed.png"), fullPage: true });
  assert.equal(await page.locator(".pm-target-row").count(), 0);
  await page.getByRole("button", { name: "查看", exact: true }).click();
  assert.equal(await page.locator(".pm-target-row").count(), 2);
  await page.getByRole("button", { name: "移除", exact: true }).first().click();
  await page.getByRole("button", { name: "确认移除", exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll(".pm-target-row").length === 1);
  assert.match(await page.locator(".pm-target-row").innerText(), /Codex/);
  const removal = await page.evaluate(() => window.__pluginCalls.find((call) => call.cmd === "plugin_market_remove_target").args);
  assert.equal(removal.targetId, "claude_code|project|F:/project/demo");
  await page.getByRole("button", { name: "返回精选目录", exact: true }).click();
  await page.locator(".pm-directory-row").nth(1).click();
  await dialog.locator(".pm-agent-options label").filter({ hasText: "Claude Code" }).getByRole("checkbox").check();
  await dialog.locator(".pm-trust input").check();
  await page.evaluate(() => window.__pluginFailure = true);
  await dialog.getByRole("button", { name: "安装到 1 个 Agent" }).click();
  await page.waitForFunction(() => document.querySelector('[role="status"]')?.textContent.includes("测试安装失败"));
  assert.ok(!(await dialog.getByRole("button", { name: "安装到 1 个 Agent" }).isDisabled()));
  await page.getByRole("button", { name: "高级", exact: true }).click();
  assert.ok(await page.getByRole("dialog", { name: "高级插件来源" }).getByRole("textbox", { name: "市场源" }).isVisible());
  await page.getByRole("button", { name: "关闭高级" }).click();
  await page.setViewportSize({ width: 600, height: 1000 });
  assert.ok(!(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)));
  await page.screenshot({ path: join(tmpdir(), "crewvela-plugin-narrow.png"), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto((process.env.CREWVELA_UI_URL || "http://127.0.0.1:1420") + "/tests/fixtures/plugin-market-ui.html?external=1");
  await page.locator(".pm-directory-row").first().click();
  await dialog.getByRole("radio", { name: "Claude 原生插件 · 全局" }).check();
  assert.ok(await dialog.getByRole("combobox", { name: "安装作用域" }).isDisabled());
  assert.ok(await dialog.locator(".pm-agent-options label").filter({ hasText: /^Codex/ }).getByRole("checkbox").isDisabled());
  assert.ok(await dialog.getByRole("button", { name: "安装到 1 个 Agent" }).isDisabled());
  await dialog.getByRole("checkbox", { name: "我已审阅并信任此来源，允许安装插件与附带代码。" }).check();
  await dialog.getByRole("button", { name: "安装到 1 个 Agent" }).click();
  await dialog.getByRole("status").waitFor();
  const native = await page.evaluate(() => window.__pluginCalls.find((call) => call.cmd === "plugin_market_install").args.input);
  assert.equal(native.mode, "native_claude"); assert.equal(native.scope, "global"); assert.equal(native.projectPath, null);
  assert.deepEqual(native.runtimes, ["claude_code"]);
  assert.match(await dialog.getByRole("status").innerText(), /原生插件安装记录已核验/);
  assert.deepEqual(errors, []);
  console.log("PASS: 分类搜索、信任/项目校验、双 Agent 安装契约、独立移除、错误恢复、高级来源、窄屏无溢出、Claude 原生模式契约");
} finally { await browser.close(); }
