import assert from "node:assert/strict";
import { mkdirSync } from "node:fs";
import { chromium } from "playwright";
const browser = await chromium.launch({ channel: "chrome", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
  page.setDefaultTimeout(10000);
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  const url = new URL("/tests/fixtures/retained-control-ui.html", process.env.CREWVELA_UI_URL || "http://127.0.0.1:1432");
  const go = mode => page.goto(new URL(`?mode=${mode}`, url).href);
  const release = (command, value, error) => page.evaluate(([command, value, error]) => window.retainedControlMock.release(command, value, error), [command, value, error]);
  const pending = command => page.waitForFunction(command => window.retainedControlMock.pending.some(item => item.command === command), command);
  const count = command => page.evaluate(command => window.retainedControlMock.calls.filter(item => item.command === command).length, command);
  await go("multi");
  const editor = page.getByPlaceholder("输入指令；使用 @ 或选择目标进入项目协作……");
  await editor.fill("hello fixture");
  await page.locator("form.multi-agent-composer").evaluate(form => { form.requestSubmit(); form.requestSubmit(); });
  await pending("fixture_quick");
  assert.equal(await count("fixture_quick"), 1);
  await release("fixture_quick", { ok: false, reply: "fixture quick rejected" });
  await page.locator(".multi-agent-error").filter({ hasText: "fixture quick rejected" }).waitFor();
  await editor.fill("original optimization prompt");
  await page.getByRole("button", { name: "优化提示词", exact: true }).click();
  await pending("optimize_prompt");
  await editor.fill("new unsent prompt");
  await release("optimize_prompt", { optimized: "obsolete suggestion", notes: "old" });
  assert.equal(await page.getByRole("dialog", { name: "提示词优化结果" }).count(), 0);
  assert.equal(await editor.inputValue(), "new unsent prompt");
  await page.getByRole("button", { name: "优化提示词", exact: true }).click();
  await pending("optimize_prompt");
  await release("optimize_prompt", { optimized: "current suggestion", notes: "new" });
  await page.getByRole("button", { name: "采纳", exact: true }).click();
  assert.equal(await editor.inputValue(), "current suggestion");
  await page.getByRole("button", { name: "快捷指挥发送目标", exact: true }).click();
  await page.getByRole("menuitemradio").filter({ hasText: "全部会话" }).click();
  await page.locator("form.multi-agent-composer").evaluate(form => { form.requestSubmit(); form.requestSubmit(); });
  await pending("fixture_broadcast"); assert.equal(await count("fixture_broadcast"), 1);
  await release("fixture_broadcast", { ok: true, reply: "fixture broadcast queued" });
  await page.locator(".multi-agent-detail-drawer > summary").click();
  await page.locator(".multi-agent-context-overview").getByText("Project-A", { exact: true }).waitFor();
  await page.evaluate(() => { window.retainedControlMock.holdB = true; });
  await page.evaluate(() => window.retainedControlMock.selectProject("B"));
  await pending("ma_snapshot");
  assert.equal(await page.locator(".multi-agent-project-summary").count(), 0, "old project snapshot cannot supply a new project's controls");
  await page.evaluate(() => window.retainedControlMock.release("ma_snapshot", window.retainedControlMock.snapshot("B")));
  await page.locator(".multi-agent-context-overview").getByText("Project-B", { exact: true }).waitFor();
  console.log("PASS: quick command/broadcast duplicate guard, prompt optimization identity and project snapshot isolation");

  await go("plan");
  const apply = page.getByRole("button", { name: "确认并启动", exact: true });
  await apply.waitFor();
  await page.waitForFunction(() => window.retainedControlMock.calls.some(item => item.command === "get_runtime_preferences"));
  await apply.evaluate(button => { button.click(); button.click(); });
  await pending("ma_apply_plan"); assert.equal(await count("ma_apply_plan"), 1);
  assert.equal(await page.getByRole("button", { name: "取消", exact: true }).isDisabled(), true);
  mkdirSync("output/playwright", { recursive: true });
  await page.screenshot({ path: "output/playwright/retained-plan-lock.png", fullPage: true });
  await release("ma_apply_plan", { projectId: "C", createdAgents: 0, createdTasks: 1 });
  await pending("ma_start_project");
  await release("ma_start_project", { projectId: "C", accepted: false, message: "fixture start refused" });
  await page.locator(".multi-agent-error").filter({ hasText: "fixture start refused" }).waitFor();
  assert.equal(await page.locator(".multi-agent-message").filter({ hasText: "计划已落地并启动" }).count(), 0);
  await go("plan-success");
  await page.getByRole("button", { name: "确认并启动", exact: true }).click();
  await pending("ma_apply_plan");
  await release("ma_apply_plan", { projectId: "C", createdAgents: 1, createdTasks: 1 });
  await pending("ma_start_project");
  await release("ma_start_project", { projectId: "C", accepted: true, message: "fixture project started" });
  await page.waitForFunction(() => !document.querySelector(".multi-agent-plan-card") && !document.querySelector(".multi-agent-composer textarea").disabled);
  assert.equal(await page.locator(".multi-agent-project-picker select").inputValue(), "C");
  assert.equal(await page.locator(".multi-agent-error").count(), 0);
  await go("plan-switch");
  await page.getByRole("button", { name: "确认并启动", exact: true }).click();
  await pending("ma_apply_plan");
  await page.evaluate(() => window.retainedControlMock.selectProject("B"));
  await release("ma_apply_plan", { projectId: "C", createdAgents: 0, createdTasks: 1 });
  await page.waitForFunction(() => !document.querySelector(".multi-agent-plan-card"));
  assert.equal(await count("ma_start_project"), 0);
  await page.locator(".multi-agent-detail-drawer > summary").click();
  assert.equal(await page.locator(".multi-agent-project-picker select").inputValue(), "B");
  await go("plan-old-failure");
  await page.getByRole("button", { name: "确认并启动", exact: true }).click();
  await pending("ma_apply_plan");
  await page.evaluate(() => window.retainedControlMock.selectProject("B"));
  await release("ma_apply_plan", null, "old project plan rejected");
  await page.waitForFunction(() => !document.querySelector(".multi-agent-composer textarea").disabled);
  assert.equal(await page.locator(".multi-agent-error").filter({ hasText: "old project plan rejected" }).count(), 0);
  console.log("PASS: plan apply is single submit, refused execution never reports started, delayed receipt cannot steal project");

  await go("settings");
  await page.locator(".collab-task-menu summary").first().click();
  const approve = page.getByRole("button", { name: "批准交付", exact: true });
  await approve.evaluate(button => { button.click(); button.click(); });
  await pending("ma_approve_task"); assert.equal(await count("ma_approve_task"), 1);
  await release("ma_approve_task", null, "fixture approval rejected");
  await page.getByRole("alert").filter({ hasText: "fixture approval rejected" }).waitFor();
  await page.waitForFunction(() => window.retainedControlMock.calls.filter(item => item.command === "ma_snapshot").length >= 2);
  assert.equal(await page.getByRole("alert").filter({ hasText: "fixture approval rejected" }).count(), 1, "background snapshot cannot hide failed mutation");
  await go("support");
  await page.getByRole("button", { name: "打开交接", exact: true }).click();
  const autofill = page.getByRole("button", { name: "自动起草（规则摘要）", exact: true });
  await autofill.evaluate(button => { button.click(); button.click(); });
  await pending("collaboration_handoff_autofill"); assert.equal(await count("collaboration_handoff_autofill"), 1);
  await page.evaluate(() => window.retainedControlMock.switchSupport("B"));
  await release("collaboration_handoff_autofill", { goal: "obsolete project notes", remaining: "old" });
  assert.equal(await page.getByLabel("目标（必填）", { exact: true }).inputValue(), "");
  await page.getByLabel(/^原会话 \/ 任务/).selectOption("B-task");
  await autofill.click(); await pending("collaboration_handoff_autofill");
  await release("collaboration_handoff_autofill", null, "fixture autofill rejected");
  const handoff = page.getByRole("dialog", { name: "交接当前工作", exact: true });
  await handoff.getByRole("alert").filter({ hasText: "fixture autofill rejected" }).waitFor();
  assert.equal(await autofill.isEnabled(), true);
  await handoff.getByLabel(/^交接类型/).selectOption("session");
  await handoff.getByLabel(/^原会话 \/ 任务/).selectOption("source");
  await handoff.getByLabel(/^接收负责人/).selectOption("target");
  await handoff.getByLabel("目标（必填）", { exact: true }).fill("new handoff");
  await handoff.getByLabel("剩余步骤（必填）", { exact: true }).fill("remaining task");
  const preview = handoff.getByRole("button", { name: "生成交接预览", exact: true });
  await preview.evaluate(button => { button.click(); button.click(); });
  await pending("collaboration_handoff_preview"); assert.equal(await count("collaboration_handoff_preview"), 1);
  const draft = { id: "handoff-new", mode: "session", projectId: null, sourceId: "source", targetId: "target", state: "preview", error: null, consequence: "Fixture only", context: "current handoff" };
  await release("collaboration_handoff_preview", draft);
  await handoff.getByRole("checkbox").check();
  const confirm = handoff.getByRole("button", { name: "确认交接", exact: true });
  await confirm.evaluate(button => { button.click(); button.click(); });
  await pending("collaboration_handoff_confirm"); assert.equal(await count("collaboration_handoff_confirm"), 1);
  await release("collaboration_handoff_confirm", { ...draft, state: "queued" });
  await handoff.getByRole("status").filter({ hasText: "目标排队中" }).waitFor();
  console.log("PASS: settings approval duplicates/failures and handoff autofill project isolation/retry");
  await go("window");
  await page.getByRole("button", { name: "重新停靠总控窗口", exact: true }).click();
  await pending("dock_control_window");
  await release("dock_control_window", null, "fixture docking rejected");
  await page.getByRole("alert").filter({ hasText: "fixture docking rejected" }).waitFor();
  assert.deepEqual(errors, []);
  mkdirSync("output/playwright", { recursive: true });
  await page.screenshot({ path: "output/playwright/retained-control-async.png", fullPage: true });
  console.log("PASS: detached control window reports docking failure without an unhandled rejection");
} finally { await browser.close(); }
