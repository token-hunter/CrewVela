// Production split view with isolated IPC; no actual installation or account access.
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
const base = process.env.CREWVELA_UI_URL || 'http://127.0.0.1:1432';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1487, height: 1058 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const url = query => `${base}/tests/fixtures/plugin-market-ui.html${query}`;
  const rows = page.locator('.pm-directory-row');
  const inspector = page.getByRole('region', { name: '插件详情与安装', exact: true });
  await page.goto(url(''));
  await inspector.getByRole('heading', { name: '网页测试', exact: true }).waitFor();
  assert.equal(await rows.count(), 16);
  await page.getByRole('button', { name: '查看 MCP 开发 详情', exact: true }).focus();
  await page.keyboard.press('Enter');
  await inspector.getByRole('heading', { name: 'MCP 开发', exact: true }).waitFor();
  await inspector.locator('.pm-trust input').check();
  const search = page.getByRole('textbox', { name: '搜索插件或使用场景' });
  await search.fill('PDF 处理');
  await inspector.getByRole('heading', { name: 'PDF 处理', exact: true }).waitFor();
  assert.equal(await inspector.locator('.pm-trust input').isChecked(), false, 'changing filtered selection resets source trust');
  assert.match(await inspector.getByRole('link', { name: '查看上游说明' }).getAttribute('href'), /\/tree\/dbd4588f9e1033efb41dad4bef2f7947c8993d44\/skills\/pdf$/);
  await search.fill('no-such-plugin');
  await inspector.waitFor({ state: 'hidden' });
  assert.equal(await page.locator('.pm-install-submit').count(), 0, 'empty results must not retain stale installation actions');
  await search.fill('');
  await inspector.getByRole('heading', { name: '网页测试', exact: true }).waitFor();
  await page.getByRole('button', { name: '待接入', exact: true }).click();
  await page.getByText('暂无待接入插件', { exact: true }).waitFor();
  await page.getByRole('button', { name: '精选', exact: true }).click();
  await page.getByRole('combobox', { name: '适用 Agent', exact: true }).selectOption('zcode');
  assert.equal(await rows.count(), 0);
  await page.getByRole('combobox', { name: '适用 Agent', exact: true }).selectOption('');
  await inspector.getByRole('heading', { name: '网页测试', exact: true }).waitFor();
  const cta = await inspector.locator('.pm-install-submit').boundingBox();
  const panel = await inspector.boundingBox();
  assert.ok(cta.y + cta.height <= panel.y + panel.height, 'default primary install action fits in the inspector');
  await inspector.getByRole('checkbox', { name: /^Claude Code/ }).check();
  const title = await inspector.getByRole('heading', { name: '网页测试', exact: true }).boundingBox();
  assert.ok(title.y >= panel.y, 'the selected plugin title remains visible while interacting with installation targets');
  mkdirSync('output/plugin-market-split', { recursive: true });
  await page.screenshot({ path: 'output/plugin-market-split/dark.png' });
  await page.evaluate(() => document.documentElement.dataset.theme = 'light');
  await page.screenshot({ path: 'output/plugin-market-split/light.png' });
  await page.setViewportSize({ width: 600, height: 1000 });
  await page.screenshot({ path: 'output/plugin-market-split/narrow.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.goto(url('?curation=1'));
  await page.getByRole('button', { name: '已安装', exact: true }).click();
  await rows.first().waitFor();
  assert.equal(await rows.count(), 3, 'installed catalogue remains available after an empty saved selection');
  await page.goto(url('?official=1'));
  await page.getByRole('button', { name: '高级', exact: true }).click();
  await page.getByRole('button', { name: '接入 OpenAI 官方候选', exact: true }).click();
  const curation = page.getByRole('dialog', { name: '挑选精选插件' });
  await curation.getByRole('checkbox', { name: '精选 GitHub（openai-curated）', exact: true }).check();
  await curation.getByRole('button', { name: '保存精选', exact: true }).click();
  await page.getByRole('button', { name: '待接入', exact: true }).click();
  await inspector.getByRole('heading', { name: 'GitHub', exact: true }).waitFor();
  assert.match(await inspector.innerText(), /需要账号授权/);
  assert.equal(await inspector.getByRole('checkbox').count(), 0);
  assert.equal(await page.locator('.pm-install-submit').count(), 0);
  assert.equal(await page.evaluate(() => window.__pluginCalls.some(call => call.cmd === 'plugin_market_install')), false);
  await page.goto(url('?load-error=1'));
  await page.getByRole('alert').filter({ hasText: '测试目录加载失败' }).waitFor();
  await page.getByRole('button', { name: '重试', exact: true }).click();
  await rows.first().waitFor();
  assert.equal(await rows.count(), 16);
  assert.deepEqual(errors, []);
  console.log('PASS: split selection, keyboard, trust reset, pinned links, empty/pending/installed views, load retry, visible CTA and themes');
} finally { await browser.close(); }
