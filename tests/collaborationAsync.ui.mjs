import assert from "node:assert/strict";
import { chromium } from "playwright";
import { mkdirSync } from "node:fs";

const browser = await chromium.launch({ channel: "chrome", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1100, height: 850 } });
  await page.addInitScript(() => Object.defineProperty(navigator, "platform", { get: () => "Win32" })); // 电脑控制段落断言 Windows 内置控制的两个后端命令；macOS 形态由 macosCore.ui.mjs 覆盖
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  const url = new URL("/tests/fixtures/collaboration-async-ui.html", process.env.CREWVELA_UI_URL || "http://127.0.0.1:1432");
  const release = (command, error) => page.evaluate(([command, error]) => window.collabMock.release(command, error), [command, error]);
  await page.goto(url.href);
  const editor = page.getByPlaceholder("人工插话（全员逐个入队；Ctrl+Enter 发送）");
  await editor.fill("submitted text");
  assert.deepEqual(await page.getByRole("combobox", { name: "发送对象" }).locator("option").allTextContents(), ["全员", "acp", "zcode", "pi"]);
  await page.getByRole("combobox", { name: "发送对象" }).selectOption("acp");
  const send = page.getByRole("button", { name: "发送", exact: true });
  await send.evaluate(button => { button.click(); button.click(); });
  await page.getByRole("button", { name: "发送中…" }).waitFor();
  assert.equal(await page.evaluate(() => window.collabMock.calls.filter(item => item.command === "send_session_message").length), 1);
  assert.equal(await page.evaluate(() => window.collabMock.pending[0].args.sessionId), "acp");
  await editor.fill("next unsent text");
  await release("send_session_message");
  await send.waitFor();
  assert.equal(await editor.inputValue(), "next unsent text");
  await send.click();
  await page.getByRole("button", { name: "切换项目" }).click();
  await page.getByText("project-B", { exact: true }).waitFor();
  await editor.fill("new project draft");
  await release("send_session_message", "old project failure");
  assert.equal(await editor.inputValue(), "new project draft");
  assert.equal(await page.getByText(/old project failure/).count(), 0);
  assert.equal(await send.isEnabled(), true);

  await page.goto(new URL("?mode=approvals", url).href);
  const allow = page.getByRole("button", { name: "允许", exact: true });
  await allow.first().waitFor();
  await allow.first().evaluate(button => { button.click(); button.click(); });
  assert.equal(await allow.nth(1).isDisabled(), true);
  assert.equal(await page.evaluate(() => window.collabMock.calls.filter(item => item.command === "respond_session_approval").length), 1);
  assert.deepEqual(await page.evaluate(() => window.collabMock.pending[0].args), { sessionId: "session-1", action: "allow", expectedPtyId: 1, expectedWaitingSince: 1001 });
  await release("respond_session_approval", "fixture decision failed");
  await page.getByText(/fixture decision failed/).waitFor();
  assert.equal(await allow.first().isEnabled(), true);
  await page.evaluate(() => { window.collabMock.holdReads = true; });
  await page.waitForFunction(() => window.collabMock.pending.filter(item => item.command === "list_approval_cards").length >= 2);
  await page.evaluate(() => window.collabMock.finishReadsNewestFirst());
  await page.getByText("目前没有待处理事项").waitFor();
  assert.equal(await page.getByRole("alert").filter({ hasText: "fixture decision failed" }).count(), 1, "polling must not erase a failed approval decision");
  assert.equal(await allow.count(), 0, "late polling cannot resurrect stale approval cards");
  await page.goto(new URL("?mode=automation", url).href);
  await page.getByRole("button", { name: "新建自动化" }).click();
  await page.getByLabel("运行方式", { exact: true }).selectOption("member");
  await page.getByLabel("目标项目", { exact: true }).selectOption("project-A");
  await page.waitForFunction(() => window.collabMock.pending.some(item => item.command === "ma_snapshot" && item.args.projectId === "project-A"));
  await page.getByLabel("目标项目", { exact: true }).selectOption("project-B");
  await page.waitForFunction(() => window.collabMock.pending.some(item => item.command === "ma_snapshot" && item.args.projectId === "project-B"));
  await page.evaluate(() => window.collabMock.releaseProject("project-B"));
  await page.getByLabel("目标成员", { exact: true }).locator('option[value="project-B-agent"]').waitFor({ state: "attached" });
  await page.evaluate(() => window.collabMock.releaseProject("project-A"));
  assert.deepEqual(await page.getByLabel("目标成员", { exact: true }).locator("option").evaluateAll(options => options.map(option => option.value)), ["", "project-B-agent"], "late project-A snapshot cannot replace project-B members");
  await page.getByLabel("目标成员", { exact: true }).selectOption("project-B-agent");
  await page.getByPlaceholder("例如：每天早上巡检依赖更新").fill("fixture schedule");
  await page.getByLabel("执行任务", { exact: true }).fill("fixture task");
  const create = page.getByRole("button", { name: "保存自动化", exact: true });
  await create.evaluate(button => { button.click(); button.click(); });
  await page.waitForFunction(() => window.collabMock.pending.some(item => item.command === "create_automation"));
  assert.equal(await page.evaluate(() => window.collabMock.calls.filter(item => item.command === "create_automation").length), 1);
  assert.equal(await page.getByPlaceholder("例如：每天早上巡检依赖更新").isDisabled(), true);
  assert.equal(await page.getByRole("button", { name: "取消", exact: true }).isDisabled(), true);
  await release("create_automation", "fixture create failed");
  await page.getByText(/fixture create failed/).waitFor();
  assert.equal(await page.getByPlaceholder("例如：每天早上巡检依赖更新").inputValue(), "fixture schedule");
  await create.click(); await release("create_automation");
  await create.waitFor({ state: "detached" });
  await page.goto(new URL("?mode=agent", url).href);
  await page.getByLabel("成员名称", { exact: true }).fill("fixture member");
  await page.getByLabel("Runtime", { exact: true }).selectOption("zcode_cli");
  const saveAgent = page.getByRole("button", { name: "保存成员", exact: true });
  await saveAgent.evaluate(button => { button.click(); button.click(); });
  assert.equal(await page.evaluate(() => window.collabMock.calls.filter(item => item.command === "fixture_save_agent").length), 1);
  assert.equal(await page.evaluate(() => window.collabMock.pending[0].args.draft.runtimeKind), "zcode_cli");
  await release("fixture_save_agent", "fixture save rejected");
  await page.getByRole("alert").filter({ hasText: "fixture save rejected" }).waitFor();
  assert.equal(await page.getByLabel("成员名称", { exact: true }).inputValue(), "fixture member");
  await saveAgent.click(); await release("fixture_save_agent");
  await page.getByText("成员已保存").waitFor();
  await page.goto(new URL("?mode=workspace", url).href);
  await page.getByRole("button", { name: /^成员/ }).click();
  const takeover = page.getByRole("button", { name: "人工接管", exact: true });
  await takeover.evaluate(button => { button.click(); button.click(); });
  assert.equal(await page.evaluate(() => window.collabMock.calls.filter(item => item.command === "ma_takeover_agent").length), 1);
  await release("ma_takeover_agent", "fixture takeover rejected");
  await page.getByRole("alert").filter({ hasText: "fixture takeover rejected" }).waitFor();
  await page.waitForFunction(() => window.collabMock.calls.filter(item => item.command === "ma_snapshot").length >= 2);
  assert.equal(await page.getByRole("alert").count(), 1, "a successful background poll must not hide an action failure");
  await takeover.click();
  await page.getByRole("button", { name: "切换项目", exact: true }).click();
  await page.getByText("project-B", { exact: true }).waitFor();
  await release("ma_takeover_agent", "old project takeover rejected");
  assert.equal(await page.getByRole("alert").count(), 0);
  await page.goto(new URL("?mode=general", url).href);
  const proxy = page.getByLabel("HTTP 代理", { exact: true });
  await proxy.waitFor();
  assert.equal(await proxy.isDisabled(), true, "initial read must finish before the default draft can overwrite saved settings");
  await release("general_settings_get", "fixture initial read failed");
  await page.getByText(/fixture initial read failed/).waitFor();
  assert.equal(await proxy.isDisabled(), true);
  await page.getByRole("button", { name: "重新读取设置", exact: true }).click();
  await page.waitForFunction(() => window.collabMock.pending.some(item => item.command === "general_settings_get"));
  await release("general_settings_get");
  await page.waitForFunction(() => !document.querySelector("#general-http-proxy").disabled && !document.querySelector("#general-http-proxy").matches(":disabled"));
  assert.equal(await page.locator("#general-terminal-font-size").inputValue(), "28", "every valid persisted font size stays representable");
  await proxy.fill("http://127.0.0.1:9000");
  const saveGeneral = page.getByRole("button", { name: "保存并应用", exact: true });
  await saveGeneral.evaluate(button => { button.click(); button.click(); });
  assert.equal(await page.evaluate(() => window.collabMock.calls.filter(item => item.command === "general_settings_save").length), 1);
  assert.equal(await proxy.isDisabled(), true);
  await release("general_settings_save", "fixture general save failed");
  await page.getByText(/fixture general save failed/).waitFor();
  assert.equal(await proxy.inputValue(), "http://127.0.0.1:9000");
  await saveGeneral.click(); await release("general_settings_save");
  await page.getByText(/已保存并应用/).waitFor();
  assert.equal(await saveGeneral.isDisabled(), true);
  await page.goto(new URL("?mode=browser", url).href);
  const channel = page.locator("#browser-control-channel");
  await channel.waitFor();
  assert.equal(await channel.isDisabled(), true);
  await release("browser_control_get", "fixture browser read failed");
  await page.getByRole("button", { name: "重新读取设置", exact: true }).click();
  await page.waitForFunction(() => window.collabMock.pending.some(item => item.command === "browser_control_get"));
  await release("browser_control_get");
  await page.locator("label").filter({ hasText: "允许 Agent 操作浏览器" }).click();
  await channel.selectOption("custom");
  const browserPath = page.getByLabel("浏览器可执行文件路径", { exact: true });
  await browserPath.fill("C:\\fixture\\browser.exe");
  const saveBrowser = page.getByRole("button", { name: "保存并应用", exact: true });
  await saveBrowser.evaluate(button => { button.click(); button.click(); });
  assert.equal(await page.evaluate(() => window.collabMock.calls.filter(item => item.command === "browser_control_save").length), 1);
  assert.equal(await browserPath.isDisabled(), true);
  await release("browser_control_save", "fixture browser save failed");
  await page.getByText(/fixture browser save failed/).waitFor();
  assert.equal(await browserPath.inputValue(), "C:\\fixture\\browser.exe");
  await saveBrowser.click(); await release("browser_control_save");
  await page.getByText("已开启浏览器控制", { exact: true }).waitFor();
  assert.equal(await saveBrowser.isDisabled(), true);
  await page.goto(new URL("?mode=computer", url).href);
  const localControl = page.getByRole("switch").nth(0);
  await localControl.waitFor();
  assert.equal(await localControl.isDisabled(), true);
  await release("computer_control_get"); await release("kimi_computer_use_get", "fixture kimi read failed");
  await page.getByText(/fixture kimi read failed/).waitFor();
  assert.equal(await localControl.isDisabled(), true);
  await page.getByRole("button", { name: "重新读取设置", exact: true }).click();
  await page.waitForFunction(() => window.collabMock.pending.some(item => item.command === "computer_control_get"));
  for (const command of ["computer_control_get", "kimi_computer_use_get"]) await release(command);
  await page.waitForFunction(() => !document.querySelector("input[role=switch]").matches(":disabled"));
  for (let i = 0; i < 2; i++) await page.locator(".browser-control-toggle").nth(i).click();
  const saveComputer = page.getByRole("button", { name: "保存并应用", exact: true });
  await saveComputer.evaluate(button => { button.click(); button.click(); });
  await release("kimi_computer_use_save", "fixture kimi save failed");
  assert.equal(await localControl.isDisabled(), true, "one early rejection must not unlock while other saves are pending");
  await release("computer_control_save");
  await page.getByText(/部分设置未保存.*fixture kimi save failed/).waitFor();
  assert.equal(await page.getByRole("switch").nth(1).isChecked(), true);
  await saveComputer.click();
  assert.deepEqual(await page.evaluate(() => window.collabMock.pending.map(item => item.command)), ["kimi_computer_use_save"], "retry only the failed backend, leaving applied settings intact");
  await release("kimi_computer_use_save");
  await page.getByText("电脑控制设置已应用", { exact: true }).waitFor();
  assert.equal(await saveComputer.isDisabled(), true);
  assert.deepEqual(errors, []);
  mkdirSync("output/playwright", { recursive: true });
  await page.screenshot({ path: "output/playwright/collaboration-async.png", fullPage: true });
  console.log("PASS: team drafts, approval identity/polling, automation, member creation, takeover and general settings async races");
} finally { await browser.close(); }
