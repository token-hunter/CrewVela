import assert from "node:assert/strict";
import { chromium } from "playwright";
import { mkdirSync } from "node:fs";
const browser = await chromium.launch({ channel: "chrome", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1100, height: 1000 } });
  page.setDefaultTimeout(10000); page.on("dialog", dialog => dialog.accept());
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  const url = new URL("/tests/fixtures/skin-pet-async-ui.html", process.env.CREWVELA_UI_URL || "http://127.0.0.1:1432");
  const release = (command, value, error) => page.evaluate(([command, value, error]) => window.skinPetMock.release(command, value, error), [command, value, error]);
  const pending = command => page.waitForFunction(command => window.skinPetMock.pending.some(item => item.command === command), command);
  const state = id => page.locator(id).textContent().then(JSON.parse);
  await page.goto(url.href);
  const importSkin = page.getByRole("button", { name: "导入皮肤", exact: true });
  await importSkin.evaluate(button => { button.click(); button.click(); });
  await pending("plugin:dialog|open");
  assert.equal(await page.evaluate(() => window.skinPetMock.calls.length), 1);
  assert.equal(await page.getByRole("button", { name: "更换 BGM", exact: true }).isDisabled(), true);
  await release("plugin:dialog|open", "/new.json"); await pending("read_skin_config_file");
  await page.locator(".skin-atmosphere-volume input").press("End");
  await release("read_skin_config_file", JSON.stringify({ name: "Imported skin", appearance: { theme: "ocean", background: "solid", accent: "blue" } }));
  await importSkin.waitFor();
  assert.equal(await page.locator(".skin-preset-card").count(), 2);
  assert.equal((await state("#skin-state")).skinSoundVolume, 100);
  const oldSkin = page.locator(".skin-preset-card").filter({ hasText: "Original skin" });
  await oldSkin.locator(".skin-custom-apply").click();
  const bgm = oldSkin.getByRole("button", { name: "更换 BGM", exact: true });
  await bgm.evaluate(button => { button.click(); button.click(); });
  await pending("plugin:dialog|open");
  assert.equal(await importSkin.isDisabled(), true);
  assert.equal(await oldSkin.getByRole("button", { name: "删除皮肤", exact: true }).isDisabled(), true);
  await release("plugin:dialog|open", "/new.mp3"); await pending("attach_dynamic_skin_audio");
  await page.locator(".skin-atmosphere-volume input").press("Home");
  await release("attach_dynamic_skin_audio", "/new-audio.mp3");
  await page.getByRole("status").filter({ hasText: "添加背景音乐" }).waitFor();
  assert.equal((await state("#skin-state")).skinSoundVolume, 0);
  assert.equal(await page.locator(".skin-preset-card").count(), 2);
  await oldSkin.getByRole("button", { name: "删除皮肤", exact: true }).click();
  await pending("delete_dynamic_skin"); await release("delete_dynamic_skin", null, "fixture deletion refused");
  await page.getByRole("status").filter({ hasText: "fixture deletion refused" }).waitFor();
  assert.equal(await page.locator(".skin-preset-card").count(), 2);
  await oldSkin.getByRole("button", { name: "删除皮肤", exact: true }).click();
  await pending("delete_dynamic_skin"); await release("delete_dynamic_skin", null);
  await page.waitForFunction(() => document.querySelectorAll(".skin-preset-card").length === 1);
  mkdirSync("output/playwright", { recursive: true });
  await page.screenshot({ path: "output/playwright/skin-import-final.png", fullPage: true });
  console.log("PASS: skin mutations serialize, retain later volume changes and preserve failed deletions");

  await page.goto(new URL("?mode=pet", url).href);
  const input = page.locator(".pet-file-input");
  const file = { name: "new-pet.png", mimeType: "image/png", buffer: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=", "base64") };
  await input.setInputFiles(file);
  await page.waitForFunction(() => window.skinPetMock.reads.length === 1);
  await input.setInputFiles({ ...file, name: "duplicate-pet.png" });
  assert.equal(await page.evaluate(() => window.skinPetMock.reads.length), 1);
  await page.getByRole("button", { name: "删除 Old pet", exact: true }).click();
  await page.locator(".pet-size-control input").press("End");
  await page.locator(".pet-choice-main").nth(1).click();
  await page.getByRole("switch", { name: "显示桌宠", exact: true }).uncheck();
  await page.evaluate(() => window.skinPetMock.readPet());
  await page.waitForFunction(() => JSON.parse(document.querySelector("#pet-state").textContent).customPets.some(item => item.name === "new-pet"));
  const saved = await state("#pet-state");
  assert.equal(saved.size, 192); assert.equal(saved.enabled, false); assert.equal(saved.selectedId, "orange-sleepy");
  assert.deepEqual(saved.customPets.map(item => item.name), ["new-pet"]);
  await input.setInputFiles({ ...file, name: "normal-pet.png" });
  await page.evaluate(() => window.skinPetMock.readPet());
  await page.waitForFunction(() => JSON.parse(document.querySelector("#pet-state").textContent).customPets.length === 2);
  assert.equal((await state("#pet-state")).enabled, true);
  assert.equal((await state("#pet-state")).customPets.at(-1).id, (await state("#pet-state")).selectedId);
  await page.screenshot({ path: "output/playwright/pet-import-final.png", fullPage: true });
  await input.setInputFiles({ ...file, name: "closed-pet.png" });
  await page.getByRole("button", { name: "关闭桌宠面板", exact: true }).click();
  await page.evaluate(() => window.skinPetMock.readPet());
  await page.waitForFunction(() => window.skinPetMock.completedReads === 3);
  assert.equal((await state("#pet-state")).customPets.length, 2);
  assert.deepEqual(errors, []);
  mkdirSync("output/playwright", { recursive: true });
  await page.screenshot({ path: "output/playwright/skin-pet-async.png", fullPage: true });
  console.log("PASS: pet import excludes duplicates, preserves concurrent edits/deletions, normally selects imported pet and ignores unmounted completion");
} finally { await browser.close(); }
