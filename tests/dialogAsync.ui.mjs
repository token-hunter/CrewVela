import assert from "node:assert/strict";
import { chromium } from "playwright";
const browser = await chromium.launch({ channel: "chrome", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1100, height: 800 } });
  page.setDefaultTimeout(10000);
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  const url = new URL("/tests/fixtures/dialog-async-ui.html", process.env.CREWVELA_UI_URL || "http://127.0.0.1:1432");
  const release = (kind, value, fail = false) => page.evaluate(({ kind, value, fail }) => window.dialogMock.release(kind, value, fail), { kind, value, fail });
  await page.goto(url.href);
  const projectName = page.getByPlaceholder("默认取目录名");
  await projectName.fill("中文输入草稿");
  for (const composition of [{ isComposing: true }, { keyCode: 229 }]) {
    await projectName.evaluate((input, composition) => input.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true, ...composition })), composition);
    assert.equal(await page.getByRole("dialog").count(), 1, "IME Escape must not dismiss the project dialog");
    assert.equal(await projectName.inputValue(), "中文输入草稿", "IME cancellation must preserve the current draft");
  }
  await projectName.press("Escape");
  await page.getByText("已关闭", { exact: true }).waitFor();
  await page.goto(url.href);
  const picker = page.getByRole("button", { name: "选择目录", exact: true });
  await picker.click();
  await release("plugin:dialog|open", "fixture picker refused", true);
  await page.getByRole("alert").filter({ hasText: "fixture picker refused" }).waitFor();
  await picker.click();
  await page.getByPlaceholder("默认取目录名").fill("手动名称");
  await release("plugin:dialog|open", "/fixture/default-name");
  assert.equal(await page.getByPlaceholder("默认取目录名").inputValue(), "手动名称");
  const submit = page.getByRole("button", { name: "添加项目", exact: true });
  await page.waitForFunction(() => Array.from(document.querySelectorAll("button")).some(button => button.textContent === "添加项目" && !button.disabled));
  await submit.evaluate(button => { button.click(); button.click(); });
  assert.equal(await page.evaluate(() => window.dialogMock.calls.filter(item => item.kind === "confirm").length), 1);
  assert.equal(await page.getByPlaceholder("默认取目录名").isDisabled(), true);
  await page.keyboard.press("Escape");
  await page.getByRole("heading", { name: "添加项目" }).waitFor();
  await release("confirm", "fixture creation refused", true);
  await page.getByRole("alert").filter({ hasText: "fixture creation refused" }).waitFor();
  assert.equal(await page.getByPlaceholder("默认取目录名").inputValue(), "手动名称");
  await submit.click(); await release("confirm", { id: "new" });
  await page.getByText("已关闭", { exact: true }).waitFor();
  await page.goto(new URL("?mode=multi", url).href);
  await page.getByRole("button", { name: "全部使用同一目录" }).click();
  assert.equal(await page.getByRole("button", { name: "开始 2 个" }).isDisabled(), true);
  await release("plugin:dialog|open", "fixture multi picker refused", true);
  await page.getByRole("alert").filter({ hasText: "fixture multi picker refused" }).waitFor();
  await page.getByRole("button", { name: "全部使用同一目录" }).click();
  await release("plugin:dialog|open", "/fixture/all");
  await page.getByRole("button", { name: "开始 2 个" }).click();
  assert.deepEqual(await page.evaluate(() => window.dialogMock.calls.at(-1).args.dirs), ["/fixture/all", "/fixture/all"]);
  await page.goto(new URL("?mode=transcript", url).href);
  await page.getByText("正在读取会话记录…", { exact: true }).waitFor();
  await release("session_transcript", [{ role: "user", text: "first transcript", at: null }]);
  await page.getByText("first transcript", { exact: true }).waitFor();
  await page.getByRole("button", { name: "切换记录" }).evaluate(button => button.click());
  await page.getByText("正在读取会话记录…", { exact: true }).waitFor();
  assert.equal(await page.getByText("first transcript", { exact: true }).count(), 0);
  await release("session_transcript", "fixture transcript failed", true);
  await page.getByText(/fixture transcript failed/).waitFor();
  await page.getByRole("button", { name: "切换记录" }).evaluate(button => button.click());
  await release("session_transcript", [{ role: "user", text: "fresh transcript", at: null }]);
  await page.getByText("fresh transcript", { exact: true }).waitFor();
  assert.equal(await page.getByText(/fixture transcript failed/).count(), 0);
  assert.deepEqual(errors, []);
  await page.screenshot({ path: "output/playwright/dialog-async.png", fullPage: true });
  await page.goto(new URL("?mode=combo", url).href);
  const combo = page.getByRole("combobox");
  await combo.fill("model");
  await page.getByRole("listbox").waitFor();
  for (const composition of [{ isComposing: true }, { keyCode: 229 }]) {
    for (const key of ["ArrowDown", "ArrowUp", "Enter", "Escape"]) {
      await combo.evaluate((input, { key, composition }) => input.dispatchEvent(new KeyboardEvent("keydown", { key, bubbles: true, ...composition })), { key, composition });
      assert.equal(await combo.inputValue(), "model", `IME ${key} must not select a model`);
      assert.equal(await page.getByRole("listbox").count(), 1, `IME ${key} must leave the dropdown open`);
      assert.equal(await page.locator(".model-combobox-option.active").innerText(), "model-one", `IME ${key} must not move the model highlight`);
    }
  }
  await combo.press("ArrowDown");
  await combo.press("Enter");
  assert.equal(await combo.inputValue(), "model-two", "ordinary keyboard selection still chooses the highlighted model");
  assert.equal(await page.getByRole("listbox").count(), 0);
  await combo.fill("model");
  await page.keyboard.press("Escape");
  await page.getByRole("listbox").waitFor({ state: "detached" });
  assert.equal(await page.getByRole("dialog").count(), 1, "first Escape closes the model dropdown only");
  await page.keyboard.press("Escape");
  await page.getByText("已关闭", { exact: true }).waitFor();
  await page.setViewportSize({ width: 520, height: 176 });
  await page.goto(new URL("?mode=notification", url).href);
  await page.waitForFunction(() => window.dialogMock.pending.some(item => item.kind === "notification_overlay_current"));
  await page.evaluate(() => window.dialogMock.emit({ title: "new notice", body: "newest body", revision: 2, url: "https://example.com" }));
  await release("notification_overlay_current", { title: "old notice", body: "old body", revision: 1, url: null });
  await page.getByRole("heading", { name: "new notice" }).waitFor();
  const view = page.getByRole("button", { name: "查看" });
  await view.evaluate(button => { button.click(); button.click(); });
  assert.equal(await page.evaluate(() => window.dialogMock.calls.filter(item => item.kind === "focus_main_from_notification").length), 1);
  await release("focus_main_from_notification", null);
  await page.waitForFunction(() => window.dialogMock.pending.some(item => item.kind === "plugin:opener|open_url"));
  await release("plugin:opener|open_url", "fixture opener refused", true);
  await page.getByText(/fixture opener refused/).waitFor();
  await page.screenshot({ path: "output/playwright/notification-error.png" });
  const notificationLayout = await page.evaluate(() => {
    const card = document.querySelector(".notification-overlay-card").getBoundingClientRect();
    const error = document.querySelector(".notification-overlay-copy [role=alert]").getBoundingClientRect();
    const button = document.querySelector(".notification-overlay-copy button").getBoundingClientRect();
    return { cardBottom: card.bottom, errorBottom: error.bottom, buttonBottom: button.bottom, height: innerHeight };
  });
  assert.ok(notificationLayout.cardBottom <= notificationLayout.height, "notification must fit native window");
  assert.ok(notificationLayout.errorBottom <= notificationLayout.cardBottom && notificationLayout.buttonBottom <= notificationLayout.cardBottom - 12, "failure and retry must remain visible");
  assert.equal(await page.evaluate(() => window.dialogMock.calls.filter(item => item.kind === "close_notification_overlay").length), 0);
  await view.click();
  await release("focus_main_from_notification", null);
  await page.waitForFunction(() => window.dialogMock.pending.some(item => item.kind === "plugin:opener|open_url"));
  await page.evaluate(() => window.dialogMock.emit({ title: "third notice", body: "keep me", revision: 3, url: null }));
  await release("plugin:opener|open_url", null);
  await page.getByRole("heading", { name: "third notice" }).waitFor();
  assert.equal(await page.evaluate(() => window.dialogMock.calls.filter(item => item.kind === "close_notification_overlay").length), 0, "old view completion must not close a new notice");
  await view.click(); await release("focus_main_from_notification", null);
  await page.waitForFunction(() => window.dialogMock.pending.some(item => item.kind === "close_notification_overlay"));
  await release("close_notification_overlay", null);
  assert.deepEqual(errors, []);
  console.log("Dialog UI passed: IME draft/dropdown protection, ordinary keyboard selection, picker failures, in-flight name edits, submit gate/recovery, batch directories and transcript identity");
} finally { await browser.close(); }
