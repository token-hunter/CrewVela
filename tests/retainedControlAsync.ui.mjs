import assert from "node:assert/strict";
import { mkdirSync } from "node:fs";
import { chromium } from "playwright";
const browser = await chromium.launch({ channel: "chrome", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
  page.setDefaultTimeout(10000);
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  const url = new URL("/tests/fixtures/retained-control-ui.html", process.env.CREWVELA_UI_URL || "http://127.0.0.1:1432");
  const go = mode => page.goto(new URL(`?mode=${mode}`, url).href);
  const release = (command, value, error) => page.evaluate(([command, value, error]) => window.retainedControlMock.release(command, value, error), [command, value, error]);
  const pending = command => page.waitForFunction(command => window.retainedControlMock.pending.some(item => item.command === command), command);
  const count = command => page.evaluate(command => window.retainedControlMock.calls.filter(item => item.command === command).length, command);
  await go("settings");
  await page.locator(".collab-task-menu summary").first().click();
  const approve = page.getByRole("button", { name: "批准交付", exact: true });
  await approve.evaluate(button => { button.click(); button.click(); });
  await pending("ma_approve_task"); assert.equal(await count("ma_approve_task"), 1);
  await release("ma_approve_task", null, "fixture approval rejected");
  await page.getByRole("alert").filter({ hasText: "fixture approval rejected" }).waitFor();
  await page.waitForFunction(() => window.retainedControlMock.calls.filter(item => item.command === "ma_snapshot").length >= 2);
  assert.equal(await page.getByRole("alert").filter({ hasText: "fixture approval rejected" }).count(), 1, "background snapshot cannot hide failed mutation");
  await go("support");
  await page.getByRole("button", { name: "打开交接", exact: true }).click();
  const autofill = page.getByRole("button", { name: "自动起草（规则摘要）", exact: true });
  await autofill.evaluate(button => { button.click(); button.click(); });
  await pending("collaboration_handoff_autofill"); assert.equal(await count("collaboration_handoff_autofill"), 1);
  await page.evaluate(() => window.retainedControlMock.switchSupport("B"));
  await release("collaboration_handoff_autofill", { goal: "obsolete project notes", remaining: "old" });
  assert.equal(await page.getByLabel("目标（必填）", { exact: true }).inputValue(), "");
  await page.getByLabel(/^原会话 \/ 任务/).selectOption("B-task");
  await autofill.click(); await pending("collaboration_handoff_autofill");
  await release("collaboration_handoff_autofill", null, "fixture autofill rejected");
  const handoff = page.getByRole("dialog", { name: "交接当前工作", exact: true });
  await handoff.getByRole("alert").filter({ hasText: "fixture autofill rejected" }).waitFor();
  assert.equal(await autofill.isEnabled(), true);
  await handoff.getByLabel(/^交接类型/).selectOption("session");
  await handoff.getByLabel(/^原会话 \/ 任务/).selectOption("source");
  await handoff.getByLabel(/^接收负责人/).selectOption("target");
  await handoff.getByLabel("目标（必填）", { exact: true }).fill("new handoff");
  await handoff.getByLabel("剩余步骤（必填）", { exact: true }).fill("remaining task");
  const preview = handoff.getByRole("button", { name: "生成交接预览", exact: true });
  await preview.evaluate(button => { button.click(); button.click(); });
  await pending("collaboration_handoff_preview"); assert.equal(await count("collaboration_handoff_preview"), 1);
  const draft = { id: "handoff-new", mode: "session", projectId: null, sourceId: "source", targetId: "target", state: "preview", error: null, consequence: "Fixture only", context: "current handoff" };
  await release("collaboration_handoff_preview", draft);
  await handoff.getByRole("checkbox").check();
  const confirm = handoff.getByRole("button", { name: "确认交接", exact: true });
  await confirm.evaluate(button => { button.click(); button.click(); });
  await pending("collaboration_handoff_confirm"); assert.equal(await count("collaboration_handoff_confirm"), 1);
  await release("collaboration_handoff_confirm", { ...draft, state: "queued" });
  await handoff.getByRole("status").filter({ hasText: "目标排队中" }).waitFor();
  console.log("PASS: settings approval duplicates/failures and handoff autofill project isolation/retry");
  await go("window");
  await page.getByRole("button", { name: "重新停靠多智能体窗口", exact: true }).click();
  await pending("dock_control_window");
  await release("dock_control_window", null, "fixture docking rejected");
  await page.getByRole("alert").filter({ hasText: "fixture docking rejected" }).waitFor();
  assert.deepEqual(errors, []);
  mkdirSync("output/playwright", { recursive: true });
  await page.screenshot({ path: "output/playwright/retained-control-async.png", fullPage: true });
  console.log("PASS: detached control window reports docking failure without an unhandled rejection");
} finally { await browser.close(); }
