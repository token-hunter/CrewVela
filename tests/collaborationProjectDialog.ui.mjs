import assert from "node:assert/strict";
import { mkdirSync } from "node:fs";
import { chromium, webkit } from "playwright";

const engine = process.env.CREWVELA_BROWSER === "webkit" ? webkit : chromium;
const browser = await engine.launch(process.env.CREWVELA_BROWSER === "webkit" ? {} : { channel: process.env.CREWVELA_BROWSER_CHANNEL });
const fixtureUrl = `${process.env.CREWVELA_UI_URL || "http://127.0.0.1:1420"}/tests/fixtures/collaboration-member-dialog-ui.html`;
mkdirSync("output/playwright", { recursive: true });
let page;
try {
  page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
  page.on("pageerror", error => console.error(error));
  await page.goto(`${fixtureUrl}?state=empty`);
  const createEntry = page.getByRole("button", { name: "创建项目", exact: true });
  await page.getByRole("status").filter({ hasText: "成员必须归属协作项目" }).waitFor();
  await page.getByRole("button", { name: "下次保存失败" }).click();
  await createEntry.click();
  const dialog = page.getByRole("dialog", { name: "创建协作项目" });
  await dialog.waitFor();
  assert.equal(await dialog.evaluate(el => el.closest(".member-fixture-host") === null), true, "project editor escapes settings clipping");
  const close = dialog.getByRole("button", { name: "关闭创建项目" });
  assert.equal(await close.evaluate(el => { const r = el.getBoundingClientRect(); return el.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)); }), true, "project close button receives clicks");
  await dialog.getByRole("button", { name: "创建项目", exact: true }).click();
  await dialog.getByRole("alert").filter({ hasText: "请填写项目名称" }).waitFor();
  assert.equal(await page.evaluate(() => window.projectMock.creates.length), 0);
  await dialog.getByLabel("项目名称", { exact: true }).fill("路径校验");
  await dialog.getByLabel("项目目录", { exact: true }).fill("relative/path");
  await dialog.getByLabel("项目目标", { exact: true }).fill("校验输入");
  await dialog.getByRole("button", { name: "创建项目", exact: true }).click();
  await dialog.getByRole("alert").filter({ hasText: "项目目录请填写本地绝对路径" }).waitFor();
  assert.equal(await page.evaluate(() => window.projectMock.creates.length), 0, "relative paths cannot create directories");
  await dialog.getByLabel("项目名称", { exact: true }).fill("");
  await page.evaluate(() => { window.projectMock.pickerResult = "/fixture/中文 空格 & project"; });
  await dialog.getByRole("button", { name: "选择目录", exact: true }).click();
  assert.equal(await dialog.getByLabel("项目名称", { exact: true }).inputValue(), "中文 空格 & project");
  assert.equal(await dialog.getByLabel("项目目录", { exact: true }).inputValue(), "/fixture/中文 空格 & project");
  await dialog.getByLabel("项目名称", { exact: true }).fill("CrewVela 协作");
  await page.evaluate(() => { window.projectMock.pickerResult = null; });
  await dialog.getByRole("button", { name: "选择目录", exact: true }).click();
  assert.equal(await dialog.getByLabel("项目目录", { exact: true }).inputValue(), "/fixture/中文 空格 & project", "picker cancel keeps the path");
  await page.evaluate(() => { window.projectMock.pickerError = true; });
  await dialog.getByRole("button", { name: "选择目录", exact: true }).click();
  await dialog.getByRole("alert").filter({ hasText: "选择目录失败" }).waitFor();
  await dialog.getByLabel("项目目标", { exact: true }).fill("修复协作入口并验证");
  await dialog.getByRole("button", { name: "创建项目", exact: true }).click();
  await dialog.getByRole("alert").filter({ hasText: "创建项目失败" }).waitFor();
  assert.equal(await dialog.getByLabel("项目名称", { exact: true }).inputValue(), "CrewVela 协作", "failed creation preserves the draft");
  await page.evaluate(() => { window.projectMock.holdCreate = true; });
  await dialog.getByRole("button", { name: "创建项目", exact: true }).dblclick();
  await dialog.getByRole("button", { name: "创建中…", exact: true }).waitFor();
  await dialog.press("Escape");
  assert.equal(await dialog.isVisible(), true, "pending creation cannot close");
  assert.equal(await page.evaluate(() => window.projectMock.creates.length), 2, "double click submits only one new request");
  await page.evaluate(() => window.projectMock.releaseCreate());
  await dialog.waitFor({ state: "detached" });
  assert.equal(await page.getByRole("combobox", { name: "当前项目" }).inputValue(), "created-project-2");
  assert.equal(await page.evaluate(() => localStorage.getItem("crewvela-multi-agent-project")), "created-project-2");
  assert.equal(await page.getByRole("tab", { name: /团队/ }).getAttribute("aria-selected"), "true");
  assert.equal(await page.getByRole("button", { name: "新增成员", exact: true }).isEnabled(), true);
  assert.deepEqual(await page.evaluate(() => window.projectMock.creates[1]), { name: "CrewVela 协作", goal: "修复协作入口并验证", rootPath: "/fixture/中文 空格 & project", defaultBranch: "main" });
  await page.getByRole("button", { name: "新增成员", exact: true }).click();
  const member = page.getByRole("dialog", { name: "新增团队成员" });
  await member.getByLabel("成员名称", { exact: true }).fill("首位成员");
  await member.getByRole("button", { name: "保存成员", exact: true }).click();
  await member.waitFor({ state: "detached" });
  assert.equal(await page.locator(".collab-agent-card").count(), 1);
  await page.screenshot({ path: "output/playwright/collaboration-project-created.png", fullPage: true });

  await page.goto(fixtureUrl);
  await page.getByRole("tab", { name: "概览", exact: true }).click();
  await createEntry.click();
  await dialog.waitFor();
  await page.screenshot({ path: "output/playwright/collaboration-create-project.png", fullPage: true });
  await dialog.press("Escape");
  await dialog.waitFor({ state: "detached" });
  assert.equal(await createEntry.evaluate(el => document.activeElement === el), true, "cancel restores focus");
  await createEntry.click();
  await dialog.getByLabel("项目名称", { exact: true }).fill("第二项目");
  await dialog.getByLabel("项目目录", { exact: true }).fill("/fixture/second");
  await dialog.getByLabel("项目目标", { exact: true }).fill("保留原项目");
  await dialog.getByRole("button", { name: "创建项目", exact: true }).click();
  await dialog.waitFor({ state: "detached" });
  assert.equal(await page.getByRole("combobox", { name: "当前项目" }).locator("option").count(), 2, "existing project is retained");
  await page.getByRole("combobox", { name: "当前项目" }).selectOption("member-fixture");
  await page.locator(".collab-agent-card").first().waitFor();
  assert.equal(await page.locator(".collab-agent-card").count(), 2);
  await page.setViewportSize({ width: 820, height: 540 });
  await createEntry.click();
  await dialog.waitFor();
  const bounds = await dialog.boundingBox();
  assert.ok(bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= 820 && bounds.y + bounds.height <= 540, "project form fits the minimum desktop viewport");
  await dialog.getByRole("button", { name: "取消", exact: true }).click();
  await dialog.waitFor({ state: "detached" });
  console.log("PASS: direct project creation, validation, picker/cancel/error, failed draft, duplicate submit guard, selection, first member and existing-project regression");
} catch (error) {
  await page?.screenshot({ path: "output/playwright/collaboration-project-failure.png", fullPage: true });
  throw error;
} finally { await browser.close(); }
