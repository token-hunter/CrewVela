import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { writeFileSync } from 'node:fs';
const base=process.env.CREWVELA_UI_URL||'http://127.0.0.1:1420';
const browser=await chromium.launch({channel:'chrome',headless:true});
try{
  const page=await browser.newPage();
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(()=>{
    window.__mascotTextures={created:0,deleted:0,peak:0};
    for(const [method,counter]of [['createTexture','created'],['deleteTexture','deleted']]){
      const original=WebGLRenderingContext.prototype[method];
      WebGLRenderingContext.prototype[method]=function(...args){window.__mascotTextures[counter]++;window.__mascotTextures.peak=Math.max(window.__mascotTextures.peak,window.__mascotTextures.created-window.__mascotTextures.deleted);return original.apply(this,args);};
    }
  });
  await page.goto(`${base}/tests/fixtures/native-mascot-ui.html?kind=claude_chat`);
  const mascot=page.locator('.native-clawd');
  await page.locator('.native-clawd[data-renderer="flow"]').waitFor();
  await page.waitForFunction(()=>window.__mascotTextures.created-window.__mascotTextures.deleted===5);
  assert.equal(await mascot.getAttribute('data-artwork-layout'),'single');
  await mascot.click();
  await page.waitForFunction(()=>Number(document.querySelector('.native-clawd').dataset.renderCount)>8);
  await page.getByLabel('播放动画').uncheck();
  const freeze=await mascot.locator('canvas').evaluate(c=>c.toDataURL());
  const draws=await mascot.getAttribute('data-render-count');
  await page.waitForTimeout(450);
  assert.equal(await mascot.locator('canvas').evaluate(c=>c.toDataURL()),freeze,'pause preserves the exact interpolated image');
  assert.equal(await mascot.getAttribute('data-render-count'),draws);
  const suspended=await page.evaluate(()=>window.__mascotTextures);
  assert.equal(suspended.created,suspended.deleted,'inactive welcome releases base and action textures');
  await page.evaluate(()=>{window.__restoreMascot=document.querySelector('.native-clawd canvas').getContext('webgl').getExtension('WEBGL_lose_context');window.__restoreMascot.loseContext();});
  await page.locator('.native-clawd[data-renderer="static-fallback"]').waitFor();
  await page.waitForTimeout(150);
  await page.evaluate(()=>window.__restoreMascot.restoreContext());
  await page.waitForFunction(()=>!document.querySelector('.native-clawd canvas').getContext('webgl').isContextLost());
  assert.deepEqual(await page.evaluate(()=>window.__mascotTextures),suspended,'restoration while inactive does not reallocate textures');
  await page.getByLabel('播放动画').check();
  await page.waitForFunction(()=>window.__mascotTextures.created-window.__mascotTextures.deleted===5);
  await page.waitForFunction(old=>Number(document.querySelector('.native-clawd').dataset.renderCount)>Number(old),draws);
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.waitForFunction(()=>window.__mascotTextures.created===window.__mascotTextures.deleted);
  assert.equal(await mascot.getAttribute('data-frame'),'0');
  const reducedDraws=await mascot.getAttribute('data-render-count');
  await page.waitForTimeout(350);
  assert.equal(await mascot.getAttribute('data-render-count'),reducedDraws);
  assert.equal(await mascot.isDisabled(),true);
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.waitForFunction(()=>window.__mascotTextures.created-window.__mascotTextures.deleted===5);
  await page.evaluate(()=>{Object.defineProperty(document,'visibilityState',{configurable:true,value:'hidden'});document.dispatchEvent(new Event('visibilitychange'));});
  await page.waitForFunction(()=>window.__mascotTextures.created===window.__mascotTextures.deleted);
  const hiddenDraws=await mascot.getAttribute('data-render-count');
  await page.waitForTimeout(350);
  assert.equal(await mascot.getAttribute('data-render-count'),hiddenDraws);
  await page.evaluate(()=>{Object.defineProperty(document,'visibilityState',{configurable:true,value:'visible'});document.dispatchEvent(new Event('visibilitychange'));});
  await page.waitForFunction(()=>window.__mascotTextures.created-window.__mascotTextures.deleted===5);
  await page.evaluate(()=>{window.__restoreMascot=document.querySelector('.native-clawd canvas').getContext('webgl').getExtension('WEBGL_lose_context');window.__restoreMascot.loseContext();});
  await page.locator('.native-clawd[data-renderer="static-fallback"]').waitFor();
  assert.equal(await mascot.isDisabled(),true);
  assert.equal(await mascot.getAttribute('title'),'动画暂不可用，正在显示静态形象');
  await page.waitForTimeout(150);
  await page.evaluate(()=>window.__restoreMascot.restoreContext());
  await page.locator('.native-clawd[data-renderer="flow"]').waitFor();
  assert.equal(await mascot.isDisabled(),false);
  await page.locator('select').selectOption('kimi_chat');
  const finalTextures=await page.evaluate(()=>window.__mascotTextures);
  assert.equal(finalTextures.created,finalTextures.deleted,'unmount and context restoration do not leak textures');
  assert.ok(finalTextures.peak<=5,'base three plus at most two HD action textures');
  await page.close();
  const reduced=await browser.newPage({reducedMotion:'reduce'});
  const requests=[];reduced.on('request',r=>requests.push({url:r.url(),type:r.resourceType()}));
  await reduced.goto(`${base}/tests/fixtures/native-mascot-ui.html?kind=claude_chat`);
  await reduced.locator('.native-clawd[data-renderer="static-paused"]').waitFor();
  assert.equal(requests.some(r=>['image','fetch'].includes(r.type)&&(/(?:flow|visibility)\.(?:png|webp)/.test(r.url)||/(?:action|motion)-\d\.webp/.test(r.url))),false,'reduced-motion initial load does not request animation textures (Vite URL import modules are scripts)');
  await reduced.close();
  const missing=await browser.newPage();
  await missing.route('**/motion-flow.webp*',route=>route.request().resourceType()==='image'?route.abort():route.continue());
  await missing.goto(`${base}/tests/fixtures/native-mascot-ui.html?kind=claude_chat`);
  await missing.locator('.native-clawd[data-renderer="static-fallback"]').waitFor();
  assert.equal(await missing.locator('.native-clawd').isDisabled(),true);
  assert.equal(await missing.locator('.native-clawd').getAttribute('title'),'动画暂不可用，正在显示静态形象');
  await missing.getByRole('button',{name:'查看命令',exact:true}).click();
  assert.match(await missing.locator('output').textContent(),/命令入口已响应/);
  await missing.close();
  const missingAction=await browser.newPage();
  await missingAction.route('**/motion-1.webp*',route=>['image','fetch'].includes(route.request().resourceType())?route.abort():route.continue());
  await missingAction.goto(`${base}/tests/fixtures/native-mascot-ui.html?kind=claude_chat`);
  await missingAction.locator('.native-clawd[data-renderer="flow"]').waitFor();
  await missingAction.locator('.native-clawd').click();
  await missingAction.locator('.native-clawd[data-renderer="static-fallback"]').waitFor();
  await missingAction.close();
  assert.deepEqual(errors,[]);
  const report={pausedPixelsFrozen:true,hiddenStopsRendering:true,reducedStatic:true,reducedSkipsDataLoad:true,textureRelease:true,activeAndInactiveContextLossAndRestore:true,missingAssetFallback:true,missingActionFallback:true,finalTextures,errors};
  writeFileSync('.scratch/mascot-smoothness-20261117/lifecycle-results.json',JSON.stringify(report,null,2));
  console.log(report);
}finally{await browser.close();}
