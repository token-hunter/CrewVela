import assert from "node:assert/strict";
import { chromium } from "playwright";
const browser = await chromium.launch({ channel: "chrome", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 850 } });
  page.setDefaultTimeout(10000);
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto(new URL("/tests/fixtures/app-session-async-ui.html", process.env.CREWVELA_UI_URL || "http://127.0.0.1:1432").href);
  await page.locator(".session-filter-trigger").click();
  await page.getByRole("option", { name: /全部/ }).click();
  const one = page.locator(".session-item").filter({ hasText: "fixture-one" });
  const two = page.locator(".session-item").filter({ hasText: "fixture-two" });
  await one.click();
  await page.waitForFunction(() => window.appSessionMock.pending.length === 1);
  await page.getByRole("button", { name: "恢复会话", exact: true }).click();
  assert.deepEqual(await page.evaluate(() => window.appSessionMock.calls), ["one"], "duplicate selection must not restart the same process twice");
  await two.click();
  await page.waitForFunction(() => window.appSessionMock.pending.length === 2);
  await page.evaluate(() => window.appSessionMock.release("one"));
  await page.getByRole("heading", { name: "fixture-two", exact: true }).waitFor();
  assert.match(await page.locator(".session-item.active").innerText(), /正在恢复/, "earlier completion cannot clear the later loading state");
  await page.getByRole("button", { name: "工作区 B", exact: true }).click();
  await page.evaluate(() => window.appSessionMock.release("two"));
  await page.locator(".empty-state").waitFor();
  assert.equal(await page.locator(".session-item.active").count(), 0);
  await page.getByRole("button", { name: "工作区 A", exact: true }).click();
  await page.locator(".pane.pane-maximized").waitFor();
  assert.match(await page.locator(".session-item.active").innerText(), /fixture-two/);
  await page.getByRole("button", { name: "工作区 A", exact: true }).dblclick();
  await page.locator(".workspace-tab-input").fill("cancelled rename");
  await page.locator(".workspace-tab-input").press("Escape");
  await page.getByRole("button", { name: "工作区 A", exact: true }).waitFor();
  assert.match(await page.locator(".session-item.active").innerText(), /fixture-two/, "Escape cancels workspace rename without leaving the current session");
  await page.locator(".session-filter-trigger").click();
  await page.keyboard.press("Escape");
  await page.getByRole("listbox", { name: "会话状态筛选" }).waitFor({ state: "detached" });
  assert.match(await page.locator(".session-item.active").innerText(), /fixture-two/);
  const search = page.getByPlaceholder("搜索标题 / 目录 / provider");
  await search.fill("fixture-two");
  await search.press("Escape");
  assert.equal(await search.inputValue(), "");
  assert.match(await page.locator(".session-item.active").innerText(), /fixture-two/, "Escape clears the search before leaving a session");
  await page.evaluate(() => window.appSessionMock.emit("app-shutdown-error", "fixture process exit unverified"));
  await page.getByText("无法安全退出：fixture process exit unverified", { exact: true }).waitFor();
  await page.locator(".unified-sidebar-settings-button").click();
  page.on("dialog", dialog => dialog.accept());
  const deleteProvider = page.getByRole("button", { name: "删除 Fixture provider", exact: true });
  await deleteProvider.click();
  await page.getByText("删除模型服务失败：Error: fixture provider delete rejected", { exact: true }).waitFor();
  assert.equal(await deleteProvider.count(), 1, "a rejected delete must preserve the provider row");
  await page.evaluate(() => { window.appSessionMock.rejectProviderDelete = false; });
  await deleteProvider.click();
  await deleteProvider.waitFor({ state: "detached" });
  assert.deepEqual(errors, []);
  await page.screenshot({ path: "output/playwright/app-session-async.png", fullPage: true });
  await page.goto(new URL("/tests/fixtures/app-session-async-ui.html?storage-full=1", process.env.CREWVELA_UI_URL || "http://127.0.0.1:1432").href);
  await page.getByText(/桌宠设置未能保存.*fixture storage full/).waitFor();
  await page.locator(".unified-sidebar-settings-button").click();
  await page.getByRole("button", { name: "删除 Fixture provider", exact: true }).waitFor();
  assert.deepEqual(errors, [], "storage failure must be visible without crashing App");
  await page.goto(new URL("/tests/fixtures/app-session-async-ui.html?retired-runtime=1", process.env.CREWVELA_UI_URL || "http://127.0.0.1:1432").href);
  await page.locator(".session-filter-trigger").click();
  await page.getByRole("option", { name: /全部/ }).click();
  await page.locator(".session-item").filter({ hasText: "fixture-one" }).click();
  await page.getByText("该运行时已移除，历史记录已保留。请使用其他 Agent 新建会话。", { exact: true }).waitFor();
  assert.equal(await page.getByRole("button", { name: "恢复会话", exact: true }).count(), 0);
  assert.deepEqual(await page.evaluate(() => window.appSessionMock.calls), []);
  assert.deepEqual(errors, []);
  await page.goto(new URL("/tests/fixtures/app-session-async-ui.html?event-error=1", process.env.CREWVELA_UI_URL || "http://127.0.0.1:1432").href);
  await page.getByText(/协作工作区事件监听失败.*fixture listener rejected/).waitFor();
  await page.getByText(/浏览器面板事件监听失败.*fixture listener rejected/).waitFor();
  assert.deepEqual(errors, [], "event subscription failures must be visible without an unhandled rejection");
  console.log("PASS: delayed session resume preserves latest selection and workspace; duplicate resume suppressed");
} finally { await browser.close(); }
