// Actual SettingsDialog and assignment form, isolated IPC only.
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
const base=process.env.CREWVELA_UI_URL||'http://127.0.0.1:1432';
const browser=await chromium.launch({channel:'chrome',headless:true});
try {
 const page=await browser.newPage({viewport:{width:1487,height:1058}});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto(`${base}/tests/fixtures/model-assignments-ui.html`);
 await page.getByRole('heading',{name:'模型设置',exact:true}).waitFor();
 const panel=page.getByRole('region',{name:'模型统一分配',exact:true});
 const edit=name=>panel.getByRole('button',{name:`编辑 ${name}`,exact:true});
 const save=panel.getByRole('button',{name:'保存更改',exact:true});
 const release=(command,error)=>page.evaluate(([command,error])=>window.__modelAssignmentMock.release(command,error),[command,error]);
 await edit('前端工程师').waitFor();
 assert.equal(await panel.locator('tbody tr:not(.model-assignment-group)').count(),9);
 await edit('前端工程师').click();
 assert.equal(await panel.getByRole('combobox',{name:'模型连接',exact:true}).count(),0,'Codex cannot use Claude provider connections');
 const input=panel.getByLabel('模型 ID',{exact:true});
 assert.equal(await input.inputValue(),'gpt-6.1-terra');
 const geometry=await page.evaluate(()=>{
  const host=document.querySelector('.settings-content'),title=document.querySelector('#settings-title'),footer=document.querySelector('.model-assignment-footer');
  return {host:host.getBoundingClientRect().toJSON(),title:title.getBoundingClientRect().toJSON(),footer:footer.getBoundingClientRect().toJSON(),overflow:host.scrollHeight-host.clientHeight};
 });
 assert.equal(geometry.overflow,0,'the table must scroll internally without pushing the settings heading away');
 assert.ok(geometry.title.top>=geometry.host.top&&geometry.footer.bottom<=geometry.host.bottom,'heading and save actions stay visible while editing');
 mkdirSync('output/model-assignments',{recursive:true});
 await page.screenshot({path:'output/model-assignments/selected-member.png'});
 await input.fill('new-member-model');
 assert.equal(await panel.getByRole('textbox',{name:'搜索成员或模型'}).isDisabled(),true);
 await page.evaluate(()=>window.__modelAssignmentMock.hold.push('model_assignments_save'));
 await save.evaluate(button=>{button.click();button.click();});
 assert.equal(await page.evaluate(()=>window.__modelAssignmentMock.calls.filter(call=>call.command==='model_assignments_save').length),1);
 await release('model_assignments_save','模拟写入失败');
 await panel.getByRole('alert').waitFor();
 assert.equal(await input.inputValue(),'new-member-model');
 await save.click();await release('model_assignments_save');
 await panel.getByRole('status').waitFor();
 assert.equal(await panel.getByLabel('模型 ID',{exact:true}).count(),0);
 assert.equal(await page.evaluate(()=>window.__modelAssignmentMock.snapshot.rows.find(row=>row.id==='session:preview-session').effective.model),'gpt-6.1-sol');
 await page.evaluate(()=>window.__modelAssignmentMock.hold=[]);
 await edit('前端工程师').click();await panel.getByRole('button',{name:'恢复继承',exact:true}).click();
 await panel.getByRole('status').filter({hasText:'恢复继承'}).waitFor();
 assert.equal(await page.evaluate(()=>window.__modelAssignmentMock.snapshot.rows.find(row=>row.id==='member:frontend').raw.model),null);
 await panel.getByRole('button',{name:'项目成员',exact:true}).click();
 assert.equal(await panel.locator('tbody tr:not(.model-assignment-group)').count(),2);
 await panel.getByRole('textbox',{name:'搜索成员或模型'}).fill('不存在');
 await panel.getByText('没有符合条件的配置。',{exact:true}).waitFor();
 assert.equal(await save.isDisabled(),true);
 await panel.getByRole('textbox',{name:'搜索成员或模型'}).fill('');
 await panel.getByRole('button',{name:'会话配置',exact:true}).click();
 await panel.getByRole('button',{name:'查看 前端页面实现',exact:true}).click();
 assert.equal(await save.isDisabled(),true);
 await edit('已停止的 Codex').click();await input.fill('session-model');await save.click();
 await panel.getByRole('status').waitFor();
 assert.equal(await page.evaluate(()=>window.__modelAssignmentMock.snapshot.rows.find(row=>row.id==='session:idle').raw.model),'session-model');
 await panel.getByRole('button',{name:'Agent 默认',exact:true}).click();
 await edit('Claude Code').click();
 await panel.getByRole('combobox',{name:'模型连接',exact:true}).selectOption('local');
 await input.fill('sonnet');await save.click();await panel.getByRole('status').waitFor();
 const saved=await page.evaluate(()=>window.__modelAssignmentMock.calls.filter(call=>call.command==='model_assignments_save').at(-1).args.input);
 assert.equal(saved.id,'runtime:claude_code');assert.equal(saved.connectionId,'local');assert.equal(saved.model,'sonnet');
 await panel.getByRole('button',{name:'管理连接',exact:true}).click();
 await page.getByRole('heading',{name:'模型服务',exact:true}).waitFor();
 await page.getByRole('button',{name:'返回模型分配',exact:true}).click();
 await edit('前端工程师').waitFor();
 await page.setViewportSize({width:820,height:700});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:'output/model-assignments/narrow.png'});
 await page.goto(`${base}/tests/fixtures/model-assignments-ui.html?theme=light`);
 await edit('前端工程师').waitFor();
 await page.screenshot({path:'output/model-assignments/light.png'});
 assert.deepEqual(errors,[]);
 console.log('PASS: real assignment form, independent connections, filter/empty, duplicate save, failure retention/retry, inheritance, live session guard, idle override, connection navigation, themes and narrow layout');
} finally {await browser.close();}
