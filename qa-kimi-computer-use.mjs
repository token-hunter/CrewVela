// Production Windows component + isolated IPC; does not operate the desktop.
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
const base = process.env.CREWVELA_UI_URL || 'http://127.0.0.1:1432';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1100, height: 900 } });
  await page.addInitScript(() => Object.defineProperty(navigator, 'platform', { value: 'Win32' }));
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${base}/tests/fixtures/settings-workspace-ui.html?page=computer`);
  const local = page.getByRole('switch', { name: /^内置电脑控制/ });
  const kimi = page.getByRole('switch', { name: /^KimiCU/ });
  const save = page.getByRole('button', { name: '保存并应用', exact: true });
  await kimi.waitFor();
  await page.waitForFunction(() => !document.querySelector('input[role=switch]').matches(':disabled'));
  assert.equal(await page.getByRole('switch').count(), 2);
  assert.equal(await local.isChecked(), true);
  assert.equal(await kimi.isChecked(), true);
  const calls = () => page.evaluate(() => window.__computerMock.calls.map(call => call.split(' ')[0]));
  assert.deepEqual(await calls(), ['computer_control_get', 'kimi_computer_use_get']);
  await local.uncheck();
  await kimi.uncheck();
  await save.click();
  await page.getByText('电脑控制设置已应用', { exact: true }).waitFor();
  assert.deepEqual((await calls()).filter(command => command.endsWith('_save')), ['computer_control_save', 'kimi_computer_use_save']);
  await page.getByRole('button', { name: '下次保存失败', exact: true }).click();
  await kimi.check();
  await save.click();
  await page.getByText(/部分设置未保存.*测试保存失败/).waitFor();
  assert.equal(await kimi.isChecked(), true, 'failed save preserves the edit for retry');
  assert.equal(await local.isChecked(), false, 'unrelated applied setting remains unchanged');
  await save.click();
  await page.getByText('电脑控制设置已应用', { exact: true }).waitFor();
  assert.equal(await save.isDisabled(), true);
  assert.equal((await calls()).filter(command => command === 'computer_control_save').length, 1);
  await page.getByText('运行时详情与安全说明', { exact: true }).click();
  mkdirSync('output/computer-control', { recursive: true });
  await page.screenshot({ path: 'output/computer-control/windows-retained.png', fullPage: true });
  await page.setViewportSize({ width: 560, height: 950 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: 'output/computer-control/windows-narrow.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('PASS: Windows retained methods, exact IPC calls, save/retry isolation and narrow layout');
} finally { await browser.close(); }
